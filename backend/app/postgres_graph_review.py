def _fingerprint(source_digest, owner, result):
    encoded = json.dumps([source_digest, owner, result], sort_keys=True,
                         ensure_ascii=False, separators=(',', ':'), default=str)
    return hashlib.sha256(encoded.encode('utf-8')).hexdigest()


def _bind_slot(digest, slot):
    # Keep fingerprints for older drafts stable when no slot was proposed.
    return _fingerprint(digest, None, slot) if slot else digest


def _snapshot(db, application_id, question):
    row, _, digest = _source(db, application_id)
    owner = db.execute('SELECT candidate_id FROM applications WHERE id=%s', (application_id,)).fetchone()['candidate_id']
    latest = db.execute('SELECT max(audit_event_id) AS id FROM hr_rubric_history WHERE application_id=%s', (application_id,)).fetchone()['id']
    result = review_graph(db, application_id, question)
    return result, _fingerprint(digest, [owner, row['status'], latest], result), latest


class ReviewState(TypedDict, total=False):
    parsed: dict
    matching: dict
    status: dict
    scheduling: dict
    policy: dict


class ApprovalState(TypedDict, total=False):
    draft_id: int
    fingerprint: str
    intent: str
    reviewed: bool
    parser_digest: str
    matching_digest: str
    status_digest: str
    scheduling_digest: str
    policy_digest: str
    matching_status: str
    application_status: str
    available_slots: bool
    interview_status: str | None
    suggested_step: str


_STAGES = ('parser', 'matching', 'status', 'scheduling', 'policy')


def _suggested_step(state):
    if state['application_status'] == 'submitted':
        return 'review_advance' if state['matching_status'] == 'current' else 'review_rubric'
    if state['application_status'] == 'advanced':
        return 'candidate_can_book' if state['available_slots'] else 'review_interview_schedule'
    return 'review_application_status'


def _suggested_step_v4(state):
    """Choose a review action based on the recorded interview lifecycle."""
    if state['application_status'] == 'advanced':
        if state['interview_status'] == 'scheduled':
            return 'review_scheduled_interview'
        if state['interview_status'] == 'completed':
            return 'review_offer_or_next_interview'
    if state['application_status'] == 'offered':
        return 'review_offer_status'
    if state['application_status'] in ('hired', 'rejected'):
        return 'review_closed_application'
    return _suggested_step(state)


def _approval_graph(db, draft=None, expected=None):
    """Only identifiers and a digest enter checkpoint storage, never excerpts.

    The caller holds the draft lock and uses this same connection for the
    checkpoint and domain changes, so either both commit or neither does.
    """
    def human_review(state: ApprovalState):
        reviewed = interrupt({'draft_id': state['draft_id'], 'intent': state['intent']})
        if not isinstance(reviewed, bool):
            raise TypeError('A boolean review decision is required')
        return {'reviewed': reviewed}

    graph = StateGraph(ApprovalState)
    saver = PostgresSaver(db)
    if draft is not None and draft['checkpoint_version'] >= 2:
        names = _STAGES
        # Resume only the paused approval node. Do not re-read an unavailable
        # source when the reviewer merely discards an obsolete draft.
        nodes = (_specialist_nodes(db, draft['application_id'], draft['question'])
                 if expected is not None else [(name, None) for name in names])
        for name, specialist in nodes:
            def record(state, specialist=specialist, name=name):
                if specialist is None:
                    raise RuntimeError('Cannot replay specialist nodes while resuming a review')
                # LangGraph may write checkpoints on a worker thread while a
                # specialist reads through this same transactional connection.
                # Share the saver's cursor lock so psycopg pipeline operations
                # and domain reads cannot overlap on that connection.
                with saver.lock:
                    result = specialist({})
                if expected is not None and result != {name if name != 'parser' else 'parsed': expected[name if name != 'parser' else 'parsed']}:
                    raise HTTPException(status_code=409, detail='Review changed while preparing; try again')
                encoded = json.dumps(result, sort_keys=True, ensure_ascii=False, separators=(',', ':'), default=str)
                update = {name + '_digest': hashlib.sha256(encoded.encode('utf-8')).hexdigest()}
                if draft['checkpoint_version'] in (3, 4):
                    # Subsequent stages consume the preceding stage's output,
                    # rather than being independent hashes of five calls.
                    prior = _STAGES.index(name)
                    if any(previous + '_digest' not in state for previous in _STAGES[:prior]):
                        raise RuntimeError('A previous specialist stage is missing')
                    if name == 'matching':
                        update['matching_status'] = result['matching']['status']
                    elif name == 'status':
                        update['application_status'] = result['status']['application_status']
                        if draft['checkpoint_version'] == 4:
                            update['interview_status'] = result['status']['latest_interview']
                    elif name == 'scheduling':
                        update['available_slots'] = bool(result['scheduling']['slots'])
                    elif name == 'policy':
                        update['suggested_step'] = (_suggested_step_v4(state) if draft['checkpoint_version'] == 4
                                                    else _suggested_step(state))
                return update
            graph.add_node(name, record)
        graph.add_edge(START, 'parser')
        for left, right in zip(('parser', 'matching', 'status', 'scheduling'), ('matching', 'status', 'scheduling', 'policy'), strict=True):
            graph.add_edge(left, right)
        graph.add_edge('policy', 'human_review')
    else:
        graph.add_edge(START, 'human_review')
    graph.add_node('human_review', human_review)
    graph.add_edge('human_review', END)
    return graph.compile(checkpointer=saver)


def _approval_config(draft_id):
    return {'configurable': {'thread_id': f'graph-review-{draft_id}'}}


def _start_approval(db, draft, expected):
    draft_id, digest, intent = draft['id'], draft['fingerprint'], draft['intent']
    result = _approval_graph(db, draft, expected).invoke(
        {'draft_id': draft_id, 'fingerprint': digest, 'intent': intent},
        _approval_config(draft_id), durability='sync')
    if len(result.get('__interrupt__', ())) != 1:
        raise RuntimeError('The review did not pause for HR approval')


def _preparation_state(db, draft):
    state = _approval_graph(db, draft).get_state(_approval_config(draft['id']))
    if (state.values.get('draft_id') != draft['id'] or
            state.values.get('fingerprint') != draft['fingerprint'] or
            state.values.get('intent') != draft['intent'] or
            len(state.next) != 1 or state.next[0] not in (*_STAGES, 'human_review')):
        raise HTTPException(status_code=409, detail='Review preparation checkpoint is unavailable or inconsistent')
    completed = [name for name in _STAGES if name + '_digest' in state.values]
    expected_completed = list(_STAGES[:_STAGES.index(state.next[0])]) if state.next[0] in _STAGES else list(_STAGES)
    if completed != expected_completed:
        raise HTTPException(status_code=409, detail='Review preparation stages are inconsistent')
    return state


def _preparation_progress(state):
    return {'completed': [name for name in _STAGES if name + '_digest' in state.values],
            'next': state.next[0], 'ready': state.next == ('human_review',) and len(state.interrupts) == 1,
            'suggested_step': state.values.get('suggested_step')}


def _advance_preparation(db, draft, expected, *, initial=False):
    graph = _approval_graph(db, draft, expected)
    config = _approval_config(draft['id'])
    if initial:
        input_value = {'draft_id': draft['id'], 'fingerprint': draft['fingerprint'], 'intent': draft['intent']}
    else:
        before = _preparation_state(db, draft)
        if before.next == ('human_review',):
            raise HTTPException(status_code=409, detail='Review preparation is already complete')
        input_value = None
    graph.invoke(input_value, config, interrupt_after=list(_STAGES), durability='sync')
    state = _preparation_state(db, draft)
    if state.next == ('human_review',) and not state.interrupts:
        graph.invoke(None, config, durability='sync')
        state = _preparation_state(db, draft)
    return _preparation_progress(state)


def _resume_approval(db, draft, reviewed, current_result=None):
    graph = _approval_graph(db, draft)
    config = _approval_config(draft['id'])
    state = graph.get_state(config)
    if (state.next != ('human_review',) or
            state.values.get('draft_id') != draft['id'] or
            state.values.get('fingerprint') != draft['fingerprint'] or
            state.values.get('intent') != draft['intent'] or
            len(state.interrupts) != 1):
        raise HTTPException(status_code=409, detail='Review checkpoint is unavailable or inconsistent')
    if draft['checkpoint_version'] in (2, 3, 4) and any(
        not isinstance(state.values.get(name + '_digest'), str)
        or len(state.values[name + '_digest']) != 64
        for name in ('parser', 'matching', 'status', 'scheduling', 'policy')
    ):
        raise HTTPException(status_code=409, detail='Specialist checkpoints are unavailable or inconsistent')
    if draft['checkpoint_version'] in (2, 3, 4) and reviewed:
        for name in ('parser', 'matching', 'status', 'scheduling', 'policy'):
            key = 'parsed' if name == 'parser' else name
            encoded = json.dumps({key: current_result[key]}, sort_keys=True, ensure_ascii=False,
                                 separators=(',', ':'), default=str)
            if state.values[name + '_digest'] != hashlib.sha256(encoded.encode('utf-8')).hexdigest():
                raise HTTPException(status_code=409, detail='Specialist checkpoint differs from the reviewed result')
        if draft['checkpoint_version'] in (3, 4):
            plan_state = {'matching_status': current_result['matching']['status'],
                'application_status': current_result['status']['application_status'],
                'available_slots': bool(current_result['scheduling']['slots']),
                'interview_status': current_result['status']['latest_interview']}
            expected_step = (_suggested_step_v4(plan_state) if draft['checkpoint_version'] == 4
                             else _suggested_step(plan_state))
            if state.values.get('suggested_step') != expected_step:
                raise HTTPException(status_code=409, detail='Specialist plan differs from the reviewed result')
    result = graph.invoke(Command(resume=reviewed), config, durability='sync')
    if result.get('reviewed') is not reviewed or result.get('__interrupt__'):
        raise RuntimeError('The review did not finish correctly')


def _specialist_nodes(db, application_id, question):
    """Build specialists over the caller's already authorized transaction."""
    row, masked, digest = _source(db, application_id)
    owner = db.execute('SELECT candidate_id FROM applications WHERE id=%s', (application_id,)).fetchone()['candidate_id']

    def parser(_state):
        structured = structure_resume(masked)
        # Section names and counts avoid copying applicant text into graph state.
        sections = structured.get('sections', {})
        return {'parsed': {'sections': {k: {'status': v['status'], 'item_count': len(v['items'])}
                                       for k, v in sections.items()}}}

    def matching(_state):
        assessment = db.execute('''SELECT audit_event_id FROM hr_rubric_history
            WHERE application_id=%s ORDER BY audit_event_id DESC LIMIT 1''', (application_id,)).fetchone()
        bounds = current_review(db, application_id, assessment['audit_event_id'], digest) if assessment else None
        return {'matching': {'status': 'current' if bounds else 'unavailable',
                             'range': list(bounds) if bounds else None}}

    def status(_state):
        interview = db.execute('''SELECT completed FROM interviews WHERE application_id=%s
            AND candidate_id=%s AND status='scheduled' ORDER BY id DESC LIMIT 1''',
            (application_id, owner)).fetchone()
        interview_state = ('completed' if interview['completed'] else 'scheduled') if interview else None
        return {'status': {'application_status': row['status'], 'job_id': row['job_id'],
                           'latest_interview': interview_state}}

    def scheduling(_state):
        # The caller takes the scheduling lock before the application lock.
        booked = db.execute("""SELECT 1 FROM interviews WHERE application_id=%s
            AND status='scheduled' AND NOT completed LIMIT 1""", (application_id,)).fetchone()
        if row['status'] != 'advanced' or booked:
            return {'scheduling': {'slots': [],
                                   'notice': 'No slot can be booked for this application now.'}}
        slots = db.execute('''SELECT id,start_at,end_at,interviewer FROM interview_slots s
            WHERE NOT withdrawn AND start_at>clock_timestamp()
            AND (target_application_id IS NULL OR (target_application_id=%s AND target_candidate_id=%s))
            AND NOT EXISTS (SELECT 1 FROM interviews i WHERE i.status='scheduled'
                AND i.start_at<s.end_at AND i.end_at>s.start_at
                AND (i.slot_id=s.id OR i.candidate_id=%s OR i.interviewer_key=s.interviewer_key))
            ORDER BY start_at,id LIMIT 20''', (application_id, owner, owner)).fetchall()
        return {'scheduling': {'slots': [dict(s) for s in slots],
                               'notice': 'Availability is a preview and may change; no booking is made.'}}

    def policy(_state):
        if not question.strip():
            return {'policy': {'status': 'not_requested', 'sources': []}}
        documents = db.execute("""SELECT id,title,body,page FROM knowledge_documents
            WHERE active AND audience IN ('public','staff','hr') AND collection='handbook'
            ORDER BY id LIMIT 500 FOR SHARE""").fetchall()
        sources = [Source(id=f"pg-doc-{d['id']}", title=d['title'], text=d['body'], page=d['page']) for d in documents]
        ranked = _rank_lexical(_tokens(question), sources)[:3]
        return {'policy': {'status': 'sources' if ranked else 'abstain',
                           'sources': [{'id': s.id, 'title': s.title, 'page': s.page, 'text': s.text} for _, s in ranked],
                           'notice': 'Extractive leads; review the original policy.'}}

    return [('parser', parser), ('matching', matching), ('status', status),
            ('scheduling', scheduling), ('policy', policy)]


def review_graph(db, application_id, question):
    graph = StateGraph(ReviewState)
    for name, node in _specialist_nodes(db, application_id, question):
        graph.add_node(name, node)
    graph.add_edge(START, 'parser')
    graph.add_edge('parser', 'matching')
    graph.add_edge('matching', 'status')
    graph.add_edge('status', 'scheduling')
    graph.add_edge('scheduling', 'policy')
    graph.add_edge('policy', END)
    return graph.compile().invoke({})


def install_routes(app, connect, authenticate, authorize_locked):
    def lock_scheduling(db):
        db.execute("SELECT pg_advisory_xact_lock(hashtext(current_schema()), hashtext('tawzeef-scheduling-v1'))")

    def validate_slot(db, application_id, slot):
        """Call under the scheduling lock and the application's row lock."""
        candidate = db.execute('''SELECT u.id FROM users u JOIN applications a ON a.candidate_id=u.id
            WHERE a.id=%s AND u.active=1 AND u.role='candidate' FOR SHARE OF u''', (application_id,)).fetchone()
        if not candidate:
            raise HTTPException(status_code=409, detail='An active candidate is required')
        if slot.start_at <= datetime.now(UTC):
            raise HTTPException(status_code=422, detail='Slot must start in the future')
        key = slot.interviewer.casefold()
        args = (slot.end_at, slot.start_at, key, candidate['id'])
        if db.execute('''SELECT 1 FROM interview_slots WHERE NOT withdrawn
            AND start_at < %s AND end_at > %s AND (interviewer_key=%s OR target_candidate_id=%s) LIMIT 1''', args).fetchone():
            raise HTTPException(status_code=409, detail='Interviewer or candidate slot conflict')
        if db.execute('''SELECT 1 FROM interviews WHERE status='scheduled'
            AND start_at < %s AND end_at > %s AND (interviewer_key=%s OR candidate_id=%s) LIMIT 1''', args).fetchone():
            raise HTTPException(status_code=409, detail='Interview conflict')
        return candidate['id'], key

    @app.post('/api/applications/{application_id}/graph-review-drafts', status_code=201)
    def start_draft(application_id: int, payload: DraftRequest, request: Request,
                    user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            lock_scheduling(db)
            result, digest, event_id = _snapshot(db, application_id, payload.policy_question)
            if payload.intent == 'advance' and (result['status']['application_status'] != 'submitted'
                                                or result['matching']['status'] != 'current' or event_id is None):
                raise HTTPException(status_code=409, detail='A submitted application and current HR rubric review are required')
            slot = payload.slot.model_dump(mode='json') if payload.slot else None
            if payload.slot:
                validate_slot(db, application_id, payload.slot)
            digest = _bind_slot(digest, slot)
            row = db.execute('''INSERT INTO graph_review_drafts(application_id,owner_id,question,fingerprint,intent,status,slot_proposal,checkpoint_version)
                VALUES (%s,%s,%s,%s,%s,'pending',%s::jsonb,2) RETURNING *''',
                (application_id, user.id, payload.policy_question, digest, payload.intent, json.dumps(slot) if slot else None)).fetchone()
            _start_approval(db, row, result)
            authorize_locked(db, request, user, 'hr')
            return {'id': row['id'], 'status': 'pending', 'intent': payload.intent, 'slot': slot, 'result': result}

    @app.post('/api/applications/{application_id}/graph-review-preparations', status_code=201)
    def begin_preparation(application_id: int, payload: DraftRequest, request: Request,
                          user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            lock_scheduling(db)
            result, digest, event_id = _snapshot(db, application_id, payload.policy_question)
            if payload.intent == 'advance' and (result['status']['application_status'] != 'submitted'
                                                or result['matching']['status'] != 'current' or event_id is None):
                raise HTTPException(status_code=409, detail='A submitted application and current HR rubric review are required')
            slot = payload.slot.model_dump(mode='json') if payload.slot else None
            if payload.slot:
                validate_slot(db, application_id, payload.slot)
            digest = _bind_slot(digest, slot)
            draft = db.execute('''INSERT INTO graph_review_drafts(application_id,owner_id,question,fingerprint,intent,status,slot_proposal,checkpoint_version)
                VALUES (%s,%s,%s,%s,%s,'pending',%s::jsonb,4) RETURNING *''',
                (application_id, user.id, payload.policy_question, digest, payload.intent, json.dumps(slot) if slot else None)).fetchone()
            progress = _advance_preparation(db, draft, result, initial=True)
            authorize_locked(db, request, user, 'hr')
            return {'id': draft['id'], 'status': 'pending', 'preparation': progress}

    def prepare_one(draft_id, request, user, *, accept_ready=False):
        """Run at most one stage and commit it before returning."""
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            lock_scheduling(db)
            draft = db.execute('SELECT * FROM graph_review_drafts WHERE id=%s AND owner_id=%s FOR UPDATE',
                               (draft_id, user.id)).fetchone()
            if not draft:
                raise HTTPException(status_code=404, detail='Review not found')
            if draft['status'] != 'pending' or draft['checkpoint_version'] not in (3, 4):
                raise HTTPException(status_code=409, detail='Review cannot be prepared')
            result, digest, _ = _snapshot(db, draft['application_id'], draft['question'])
            if _bind_slot(digest, draft['slot_proposal']) != draft['fingerprint']:
                raise HTTPException(status_code=409, detail='Review changed; discard it and start again')
            state = _preparation_state(db, draft)
            if accept_ready and _preparation_progress(state)['ready']:
                authorize_locked(db, request, user, 'hr')
                return {'id': draft_id, 'status': 'pending', 'preparation': _preparation_progress(state)}
            progress = _advance_preparation(db, draft, result)
            authorize_locked(db, request, user, 'hr')
            return {'id': draft_id, 'status': 'pending', 'preparation': progress}

    @app.post('/api/graph-review-drafts/{draft_id}/prepare')
    def continue_preparation(draft_id: int, request: Request, user: Annotated[User, Depends(authenticate)]):
        return prepare_one(draft_id, request, user)

    @app.post('/api/graph-review-drafts/{draft_id}/prepare-all')
    def prepare_all(draft_id: int, request: Request, user: Annotated[User, Depends(authenticate)]):
        # Every call has its own DB transaction. A failure keeps earlier stages
        # committed and retryable; each stage rechecks authorization and sources.
        for _ in range(len(_STAGES) + 1):
            result = prepare_one(draft_id, request, user, accept_ready=True)
            if result['preparation']['ready']:
                return result
        raise HTTPException(status_code=409, detail='Review preparation did not finish')

    @app.get('/api/applications/{application_id}/graph-review-drafts')
    def list_drafts(application_id: int, request: Request, user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            rows = db.execute('''SELECT id,status,created_at FROM graph_review_drafts
                WHERE application_id=%s AND owner_id=%s ORDER BY id DESC LIMIT 20 FOR SHARE''',
                (application_id, user.id)).fetchall()
            authorize_locked(db, request, user, 'hr')
            return [dict(row) for row in rows]

    @app.get('/api/graph-review-drafts/{draft_id}')
    def read_draft(draft_id: int, request: Request, user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            lock_scheduling(db)
            draft = db.execute('SELECT * FROM graph_review_drafts WHERE id=%s AND owner_id=%s FOR UPDATE',
                               (draft_id, user.id)).fetchone()
            if draft is None:
                raise HTTPException(status_code=404, detail='Review not found')
            try:
                result, digest, _ = _snapshot(db, draft['application_id'], draft['question'])
            except HTTPException as exc:
                if exc.status_code not in (404, 422):
                    raise
                authorize_locked(db, request, user, 'hr')
                return {'id': draft_id, 'status': draft['status'], 'intent': draft['intent'], 'stale': True}
            digest = _bind_slot(digest, draft['slot_proposal'])
            authorize_locked(db, request, user, 'hr')
            if digest != draft['fingerprint']:
                return {'id': draft_id, 'status': draft['status'], 'intent': draft['intent'], 'stale': True}
            response = {'id': draft_id, 'status': draft['status'], 'intent': draft['intent'], 'slot': draft['slot_proposal'], 'stale': False, 'result': result}
            if draft['checkpoint_version'] in (3, 4) and draft['status'] == 'pending':
                response['preparation'] = _preparation_progress(_preparation_state(db, draft))
                authorize_locked(db, request, user, 'hr')
            return response

    @app.post('/api/graph-review-drafts/{draft_id}/resume')
    def resume_draft(draft_id: int, payload: ReviewReply, request: Request,
                     user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            lock_scheduling(db)
            draft = db.execute('SELECT * FROM graph_review_drafts WHERE id=%s AND owner_id=%s FOR UPDATE',
                               (draft_id, user.id)).fetchone()
            if draft is None:
                raise HTTPException(status_code=404, detail='Review not found')
            if draft['status'] != 'pending':
                raise HTTPException(status_code=409, detail='Review is already closed')
            if (draft['checkpoint_version'] in (3, 4) and payload.reviewed and
                    not _preparation_progress(_preparation_state(db, draft))['ready']):
                raise HTTPException(status_code=409, detail='Finish review preparation before approval')
            if payload.reviewed:
                result, digest, event_id = _snapshot(db, draft['application_id'], draft['question'])
                digest = _bind_slot(digest, draft['slot_proposal'])
                if digest != draft['fingerprint']:
                    raise HTTPException(status_code=409, detail='Review changed; start a new review')
                if draft['intent'] == 'advance':
                    if result['status']['application_status'] != 'submitted' or result['matching']['status'] != 'current' or event_id is None:
                        raise HTTPException(status_code=409, detail='A current HR rubric review is required')
                    if not db.execute('''SELECT 1 FROM users u JOIN applications a ON a.candidate_id=u.id
                        WHERE a.id=%s AND u.active=1 AND u.role='candidate' FOR SHARE OF u''',
                                      (draft['application_id'],)).fetchone():
                        raise HTTPException(status_code=409, detail='An active candidate is required')
                    slot = SlotCreate.model_validate(draft['slot_proposal']) if draft['slot_proposal'] else None
                    if slot:
                        candidate_id, key = validate_slot(db, draft['application_id'], slot)
                    db.execute("""UPDATE applications SET status='advanced', updated_at=to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"') WHERE id=%s""", (draft['application_id'],))
                    db.execute("INSERT INTO audit_events(application_id,actor_id,action,details) VALUES (%s,%s,'decision',%s)",
                               (draft['application_id'], user.id, json.dumps({'decision': 'advance', 'rubric_event_id': event_id, 'draft_id': draft_id})))
                    if slot:
                        created = db.execute('''INSERT INTO interview_slots(start_at,end_at,interviewer,interviewer_key,created_by,
                            target_application_id,target_candidate_id) VALUES (%s,%s,%s,%s,%s,%s,%s) RETURNING id''',
                            (slot.start_at, slot.end_at, slot.interviewer, key, user.id, draft['application_id'], candidate_id)).fetchone()
                        db.execute("INSERT INTO slot_audit_events(slot_id,actor_id,action) VALUES (%s,%s,'created_private')", (created['id'], user.id))
            if draft['checkpoint_version'] not in (0, 1, 2, 3, 4):
                raise HTTPException(status_code=409, detail='Unsupported review checkpoint version')
            if draft['checkpoint_version'] in (1, 2) or (draft['checkpoint_version'] in (3, 4) and payload.reviewed):
                _resume_approval(db, draft, payload.reviewed, result if payload.reviewed else None)
            status = 'reviewed' if payload.reviewed else 'discarded'
            db.execute('UPDATE graph_review_drafts SET status=%s WHERE id=%s', (status, draft_id))
            db.execute("INSERT INTO audit_events(application_id,actor_id,action,details) VALUES (%s,%s,%s,%s)",
                       (draft['application_id'], user.id, 'graph_review_' + status, json.dumps({'draft_id': draft_id})))
            authorize_locked(db, request, user, 'hr')
            notice = 'Application advanced by HR.' if payload.reviewed and draft['intent'] == 'advance' else 'No recruitment decision was made.'
            if payload.reviewed and draft['slot_proposal']:
                notice = 'Application advanced and a private slot reserved by HR; the candidate must book it.'
            return {'id': draft_id, 'status': status, 'notice': notice}

    @app.post('/api/applications/{application_id}/graph-review')
    def graph_review(application_id: int, payload: ReviewRequest, request: Request,
                     user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            # Match the order used by scheduling writes to avoid lock inversion.
            db.execute("SELECT pg_advisory_xact_lock(hashtext(current_schema()), hashtext('tawzeef-scheduling-v1'))")
            result = review_graph(db, application_id, payload.policy_question)
            authorize_locked(db, request, user, 'hr')
            return {'application_id': application_id, **result,
                    'notice': 'Read-only local review; HR must make all decisions separately.'}
