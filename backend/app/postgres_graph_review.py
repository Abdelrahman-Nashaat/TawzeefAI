    @app.post('/api/applications/{application_id}/adaptive-review-preparations', status_code=201)
    def begin_adaptive_preparation(application_id: int, payload: AdaptiveDraftRequest, request: Request,
                                   user: Annotated[User, Depends(authenticate)]):
        if payload.model_plan and (os.environ.get('TAWZEEF_POSTGRES_ENABLE_GROQ') != '1'
                                   or not os.environ.get('GROQ_API_KEY', '').strip()):
            raise HTTPException(status_code=503, detail='External AI planning is not configured')
        # Do not hold a database transaction across a provider request. Compare
        # the complete review snapshot and reauthorize before storing its plan.
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            lock_scheduling(db)
            result, digest, _ = _snapshot(db, application_id, payload.policy_question, all_collections=True,
                                          stages=['matching', 'status'])
            authorize_locked(db, request, user, 'hr')
        if payload.model_plan and not _AI_PLAN_BUSY.acquire(blocking=False):
            raise HTTPException(status_code=429, detail='External AI planning is busy')
        try:
            try:
                plan, source = _adaptive_steps(result, payload.intent, payload.policy_question, model=payload.model_plan)
                if payload.keyword_preview:
                    if 'parser' not in plan:
                        plan.insert(0, 'parser')
                    if 'matching' not in plan:
                        plan.insert(plan.index('parser') + 1, 'matching')
            except (ValueError, TypeError):
                raise HTTPException(status_code=503, detail='Adaptive planning is unavailable') from None
        finally:
            if payload.model_plan:
                _AI_PLAN_BUSY.release()
        if source not in ('deterministic', 'deterministic_fallback', 'model'):
            raise HTTPException(status_code=503, detail='Adaptive planning is unavailable')
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            lock_scheduling(db)
            preflight, current_digest, _ = _snapshot(db, application_id, payload.policy_question, all_collections=True,
                                                     stages=['matching', 'status'])
            if current_digest != digest or preflight != result:
                raise HTTPException(status_code=409, detail='Review changed; start again')
            current, digest, event_id = _snapshot(db, application_id, payload.policy_question,
                                                  all_collections=True, stages=plan, keyword_preview=payload.keyword_preview)
            if payload.intent == 'advance' and (current['status']['application_status'] != 'submitted'
                                                or current['matching']['status'] != 'current' or event_id is None):
                raise HTTPException(status_code=409, detail='A submitted application and current HR rubric review are required')
            if payload.intent == 'reserve_slot' and current['status']['application_status'] != 'advanced':
                raise HTTPException(status_code=409, detail='An advanced application is required')
            if payload.intent == 'present_offer':
                validate_offer(db, application_id)
            slot = payload.slot.model_dump(mode='json') if payload.slot else None
            if payload.slot:
                validate_slot(db, application_id, payload.slot)
            digest = _bind_proposal(digest, slot, payload.offer_details)
            draft = db.execute('''INSERT INTO graph_review_drafts(application_id,owner_id,question,fingerprint,intent,status,
                slot_proposal,offer_details,checkpoint_version,adaptive_plan,adaptive_plan_source)
                VALUES (%s,%s,%s,%s,%s,'pending',%s::jsonb,%s,%s,%s::jsonb,%s) RETURNING *''',
                (application_id, user.id, payload.policy_question, digest, payload.intent,
                 json.dumps(slot) if slot else None, payload.offer_details, 7 if payload.keyword_preview else 6, json.dumps(plan), source)).fetchone()
            progress = _advance_preparation(db, draft, current, initial=True)
            authorize_locked(db, request, user, 'hr')
            return {'id': draft['id'], 'status': 'pending', 'plan': plan, 'plan_source': source,
                    'preparation': progress}

    def prepare_one(draft_id, request, user, *, accept_ready=False):
        """Run at most one stage and commit it before returning."""
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            lock_scheduling(db)
            draft = db.execute('SELECT * FROM graph_review_drafts WHERE id=%s AND owner_id=%s FOR UPDATE',
                               (draft_id, user.id)).fetchone()
            if not draft:
                raise HTTPException(status_code=404, detail='Review not found')
            if draft['status'] != 'pending' or draft['checkpoint_version'] not in (3, 4, 5, 6, 7):
                raise HTTPException(status_code=409, detail='Review cannot be prepared')
            result, digest, _ = _snapshot(db, draft['application_id'], draft['question'],
                                          all_collections=draft['checkpoint_version'] >= 5,
                                          stages=_stages(draft) if draft['checkpoint_version'] in (6, 7) else None,
                                          keyword_preview=draft['checkpoint_version'] == 7)
            if _bind_proposal(digest, draft['slot_proposal'], draft['offer_details']) != draft['fingerprint']:
                raise HTTPException(status_code=409, detail='Review changed; discard it and start again')
            state = _preparation_state(db, draft)
            if accept_ready and _preparation_progress(state)['ready']:
                authorize_locked(db, request, user, 'hr')
                return {'id': draft_id, 'status': 'pending', 'preparation': _preparation_progress(state)}
            progress = _advance_preparation(db, draft, result)
            authorize_locked(db, request, user, 'hr')
            return {'id': draft_id, 'status': 'pending', 'preparation': progress}

    @app.post('/api/graph-review-drafts/{draft_id}/prepare')
    def continue_preparation(draft_id: int, request: Request, user: Annotated[User, Depends(authenticate)]):
        return prepare_one(draft_id, request, user)

    @app.post('/api/graph-review-drafts/{draft_id}/prepare-all')
    def prepare_all(draft_id: int, request: Request, user: Annotated[User, Depends(authenticate)]):
        # Every call has its own DB transaction. A failure keeps earlier stages
        # committed and retryable; each stage rechecks authorization and sources.
        for _ in range(len(_STAGES) + 1):
            result = prepare_one(draft_id, request, user, accept_ready=True)
            if result['preparation']['ready']:
                return result
        raise HTTPException(status_code=409, detail='Review preparation did not finish')

    def ai_context(draft_id, request, user):
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            lock_scheduling(db)
            draft = db.execute('SELECT * FROM graph_review_drafts WHERE id=%s AND owner_id=%s FOR UPDATE',
                               (draft_id, user.id)).fetchone()
            if not draft:
                raise HTTPException(status_code=404, detail='Review not found')
            if draft['status'] != 'pending' or draft['checkpoint_version'] not in (3, 4, 5):
                raise HTTPException(status_code=409, detail='A pending resumable review is required')
            result, digest, _ = _snapshot(db, draft['application_id'], draft['question'],
                                          all_collections=draft['checkpoint_version'] >= 5)
            if _bind_proposal(digest, draft['slot_proposal'], draft['offer_details']) != draft['fingerprint']:
                raise HTTPException(status_code=409, detail='Review changed; start again')
            state = _preparation_state(db, draft)
            if not _preparation_progress(state)['ready']:
                raise HTTPException(status_code=409, detail='Finish preparation before requesting a suggestion')
            status = result['status']['application_status']
            matching = result['matching']['status']
            interview = result['status']['latest_interview']
            available = bool(result['scheduling']['slots'])
            if (status not in ('submitted', 'advanced', 'offered', 'hired', 'rejected') or
                    matching not in ('current', 'unavailable') or interview not in (None, 'scheduled', 'completed')):
                raise HTTPException(status_code=409, detail='Review status is unavailable')
            facts = {'application_status': status, 'assessment_status': matching,
                     'interview_status': interview, 'has_available_slot': available}
            authorize_locked(db, request, user, 'hr')
            return facts, allowed_actions(status, matching, interview, available), draft['fingerprint']

    @app.post('/api/graph-review-drafts/{draft_id}/ai-suggestion')
    def ai_suggestion(draft_id: int, request: Request, user: Annotated[User, Depends(authenticate)]):
        if os.environ.get('TAWZEEF_POSTGRES_ENABLE_GROQ') != '1' or not os.environ.get('GROQ_API_KEY', '').strip():
            raise HTTPException(status_code=503, detail='External AI suggestions are not configured')
        if not _AI_PLAN_BUSY.acquire(blocking=False):
            raise HTTPException(status_code=429, detail='External AI suggestions are busy')
        try:
            facts, actions, fingerprint = ai_context(draft_id, request, user)
            try:
                action = request_plan(facts, actions)
            except ProviderUnavailable as exc:
                raise HTTPException(status_code=503, detail='External AI suggestion unavailable') from exc
            if action not in actions:
                raise HTTPException(status_code=503, detail='External AI suggestion unavailable')
            current_facts, current_actions, current_fingerprint = ai_context(draft_id, request, user)
            if (current_fingerprint != fingerprint or current_facts != facts or
                    current_actions != actions or action not in current_actions):
                raise HTTPException(status_code=409, detail='Review changed; reopen it before continuing')
            return {'suggested_step': action, 'notice': 'AI suggestion based only on status flags. HR must review the evidence and decide; no action was taken.'}
        finally:
            _AI_PLAN_BUSY.release()

