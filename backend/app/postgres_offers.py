"""Recipient-bound offers in the synthetic PostgreSQL-only demo."""
import json
from typing import Annotated, Literal

from fastapi import Depends, HTTPException, Request
from pydantic import BaseModel, Field

from app.auth import User

DDL = (
    '''CREATE TABLE IF NOT EXISTS job_offers (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        application_id bigint NOT NULL REFERENCES applications(id),
        recipient_id bigint NOT NULL REFERENCES users(id),
        details text NOT NULL CHECK (length(details) BETWEEN 1 AND 4000),
        status text NOT NULL CHECK (status IN ('presented','accepted','declined','withdrawn')),
        created_by bigint NOT NULL REFERENCES users(id),
        created_at timestamptz NOT NULL DEFAULT clock_timestamp(), responded_at timestamptz)''',
    "CREATE UNIQUE INDEX IF NOT EXISTS current_job_offer ON job_offers(application_id) WHERE status IN ('presented','accepted')",
)


class OfferCreate(BaseModel):
    details: str = Field(min_length=1, max_length=4000)


class OfferReply(BaseModel):
    decision: Literal['accepted', 'declined']


_FIELDS = 'id,application_id,recipient_id,details,status,created_at,responded_at'


def _audit(db, application, actor, action, offer):
    db.execute('INSERT INTO audit_events(application_id,actor_id,action,details) VALUES (%s,%s,%s,%s)',
               (application, actor, action, json.dumps({'offer_id': offer})))


def _update_application(db, application, status):
    db.execute('''UPDATE applications SET status=%s,
        updated_at=to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
        WHERE id=%s''', (status, application))


def hire(db, application_id, user, note):
    """Called under the scheduling lock and an authenticated HR transaction."""
    application = db.execute('SELECT * FROM applications WHERE id=%s FOR UPDATE', (application_id,)).fetchone()
    if not application:
        raise HTTPException(status_code=404, detail='Application not found')
    if application['status'] != 'offered':
        raise HTTPException(status_code=409, detail='Application is not ready for hiring')
    if not db.execute("SELECT 1 FROM users WHERE id=%s AND role='candidate' AND active=1 FOR SHARE",
                      (application['candidate_id'],)).fetchone():
        raise HTTPException(status_code=409, detail='An active candidate account is required')
    offer = db.execute("""SELECT id FROM job_offers WHERE application_id=%s AND recipient_id=%s
        AND status='accepted' FOR UPDATE""", (application_id, application['candidate_id'])).fetchone()
    if not offer:
        raise HTTPException(status_code=409, detail='Candidate must accept an offer before hiring')
    _update_application(db, application_id, 'hired')
    db.execute("INSERT INTO audit_events(application_id,actor_id,action,details) VALUES (%s,%s,'decision',%s)",
               (application_id, user.id, json.dumps({'decision': 'hire', 'note': note}, ensure_ascii=False)))
    return db.execute('SELECT * FROM applications WHERE id=%s', (application_id,)).fetchone()


def install_routes(app, connect, authenticate, authorize_locked, guard):
    @app.get('/api/applications/{application_id}/offers')
    def list_offers(application_id: int, request: Request, user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user)
            if user.role == 'candidate':
                application = db.execute('SELECT id FROM applications WHERE id=%s AND candidate_id=%s FOR SHARE',
                                         (application_id, user.id)).fetchone()
                if not application:
                    raise HTTPException(status_code=404, detail='Application not found')
                rows = db.execute(f'SELECT {_FIELDS} FROM job_offers WHERE application_id=%s AND recipient_id=%s ORDER BY id DESC FOR SHARE',
                                  (application_id, user.id)).fetchall()
            elif user.role == 'hr':
                application = db.execute('SELECT id FROM applications WHERE id=%s FOR SHARE', (application_id,)).fetchone()
                if not application:
                    raise HTTPException(status_code=404, detail='Application not found')
                rows = db.execute(f'SELECT {_FIELDS} FROM job_offers WHERE application_id=%s ORDER BY id DESC FOR SHARE',
                                  (application_id,)).fetchall()
            else:
                raise HTTPException(status_code=403, detail='Access denied')
            authorize_locked(db, request, user)
            return [dict(row) for row in rows]

    @app.post('/api/applications/{application_id}/offers', status_code=201)
    def create_offer(application_id: int, payload: OfferCreate, request: Request, user: Annotated[User, Depends(authenticate)]):
        details = payload.details.strip()
        if not details:
            raise HTTPException(status_code=422, detail='Offer details are required')
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            guard(db)
            application = db.execute('SELECT * FROM applications WHERE id=%s FOR UPDATE', (application_id,)).fetchone()
            if not application:
                raise HTTPException(status_code=404, detail='Application not found')
            if application['status'] != 'advanced':
                raise HTTPException(status_code=409, detail='Application is not ready for an offer')
            if not db.execute("SELECT 1 FROM users WHERE id=%s AND role='candidate' AND active=1 FOR SHARE", (application['candidate_id'],)).fetchone():
                raise HTTPException(status_code=409, detail='An active candidate account is required')
            if not db.execute("SELECT 1 FROM interviews WHERE application_id=%s AND candidate_id=%s AND completed AND status='scheduled' LIMIT 1", (application_id, application['candidate_id'])).fetchone():
                raise HTTPException(status_code=409, detail='A completed interview is required')
            if db.execute("SELECT 1 FROM interviews WHERE application_id=%s AND status='scheduled' AND end_at>clock_timestamp() LIMIT 1", (application_id,)).fetchone():
                raise HTTPException(status_code=409, detail='Resolve active interviews before presenting an offer')
            row = db.execute(f"INSERT INTO job_offers(application_id,recipient_id,details,status,created_by) VALUES (%s,%s,%s,'presented',%s) RETURNING {_FIELDS}",
                             (application_id, application['candidate_id'], details, user.id)).fetchone()
            _update_application(db, application_id, 'offered')
            _audit(db, application_id, user.id, 'offer_presented', row['id'])
            authorize_locked(db, request, user, 'hr')
            return dict(row)

    def resolve_offer(db, offer_id, user, candidate):
        row = db.execute('''SELECT o.*,a.status AS application_status,a.candidate_id FROM job_offers o
            JOIN applications a ON a.id=o.application_id WHERE o.id=%s FOR UPDATE OF o,a''', (offer_id,)).fetchone()
        if not row or (candidate and (row['recipient_id'] != user.id or row['candidate_id'] != user.id)):
            raise HTTPException(status_code=404, detail='Offer not found')
        if row['recipient_id'] != row['candidate_id']:
            raise HTTPException(status_code=409, detail='Offer ownership changed')
        if row['status'] != 'presented' or row['application_status'] != 'offered':
            raise HTTPException(status_code=409, detail='Offer is no longer awaiting a response')
        return row

    @app.post('/api/offers/{offer_id}/respond')
    def respond_offer(offer_id: int, payload: OfferReply, request: Request, user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user, 'candidate')
            guard(db)
            offer = resolve_offer(db, offer_id, user, True)
            row = db.execute(f'UPDATE job_offers SET status=%s,responded_at=clock_timestamp() WHERE id=%s RETURNING {_FIELDS}',
                             (payload.decision, offer_id)).fetchone()
            if payload.decision == 'declined':
                _update_application(db, offer['application_id'], 'advanced')
            _audit(db, offer['application_id'], user.id, 'offer_' + payload.decision, offer_id)
            authorize_locked(db, request, user, 'candidate')
            return dict(row)

    @app.post('/api/offers/{offer_id}/withdraw')
    def withdraw_offer(offer_id: int, request: Request, user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            guard(db)
            offer = resolve_offer(db, offer_id, user, False)
            row = db.execute(f"UPDATE job_offers SET status='withdrawn',responded_at=clock_timestamp() WHERE id=%s RETURNING {_FIELDS}", (offer_id,)).fetchone()
            _update_application(db, offer['application_id'], 'advanced')
            _audit(db, offer['application_id'], user.id, 'offer_withdrawn', offer_id)
            authorize_locked(db, request, user, 'hr')
            return dict(row)
