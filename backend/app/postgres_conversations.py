class Turn(Metadata):
    question: str = Field(min_length=1, max_length=2000)
    collection: Literal['handbook', 'job_description', 'past_hire_patterns'] | None = None
    generate_answer: bool = False
    experimental_hybrid: bool = False


def _digest(row):
    value = [row['id'], row['title'], row['body'], row['page'], row['collection'], row['audience']]
    if row['job_id'] is not None or row['section'] is not None:
        value.extend([row['job_id'], row['section']])
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, separators=(',', ':')).encode()).hexdigest()


def _documents(db, role, job_id=None, section=None, collection=None):
    return db.execute('''SELECT id,title,body,page,collection,audience,job_id,section FROM knowledge_documents
        WHERE active AND audience=ANY(%s) AND (collection <> 'past_hire_patterns' OR %s='hr')
        AND (%s::text IS NULL OR job_id=%s) AND (%s::text IS NULL OR section=%s)
        AND (%s::text IS NULL OR collection=%s)
        ORDER BY id LIMIT 500 FOR SHARE''',
        (list(ROLE_AUDIENCES[role]), role, job_id, job_id, section, section, collection, collection)).fetchall()


def _reconstruct(ref, docs):
    if not isinstance(ref, dict) or set(ref) not in ({'id', 'digest'}, {'id', 'digest', 'passage_id'}):
        return None
    row = docs.get(ref['id'])
    if row is None or _digest(row) != ref['digest']:
        return None
    if 'passage_id' in ref:
        passages = _document_passages({'id': row['id'], 'title': row['title'], 'text': row['body']})
        passage = next((p for p in passages if p.id == ref['passage_id']), None)
        if passage is None:
            return None
        source = Source(id=passage.id, title=passage.title, text=passage.text, page=row['page'])
    else:
        source = Source(id=f"pg-doc-{row['id']}", title=row['title'], text=row['body'], page=row['page'])
    return source_dict(source, {source.id: row})


def _owner(db, conversation_id, user):
    row = db.execute('''SELECT id FROM knowledge_conversations
        WHERE id=%s AND owner_id=%s AND role=%s FOR UPDATE''',
        (conversation_id, user.id, user.role)).fetchone()
    if not row:
        raise HTTPException(status_code=404, detail='Conversation not found')


def install_routes(app, connect, authenticate, authorize_locked):
    @app.post('/api/knowledge/conversations', status_code=201)
    def create(request: Request, user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user)
            # Serialize this user's bounded create check across requests.
            db.execute("SELECT pg_advisory_xact_lock(hashtext(current_schema()), hashtext(%s))",
                       (f'knowledge-conversations:{user.id}',))
            count = db.execute('SELECT count(*) AS n FROM knowledge_conversations WHERE owner_id=%s', (user.id,)).fetchone()['n']
            if count >= 100:
                raise HTTPException(status_code=409, detail='Conversation limit reached')
            row = db.execute('INSERT INTO knowledge_conversations(owner_id,role) VALUES (%s,%s) RETURNING id,created_at',
                             (user.id, user.role)).fetchone()
            authorize_locked(db, request, user)
            return dict(row)

    @app.get('/api/knowledge/conversations')
    def list_conversations(request: Request, user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user)
            rows = db.execute('''SELECT id,created_at FROM knowledge_conversations
                WHERE owner_id=%s AND role=%s ORDER BY id DESC LIMIT 100 FOR SHARE''',
                (user.id, user.role)).fetchall()
            authorize_locked(db, request, user)
            return {'items': [dict(row) for row in rows]}

    @app.delete('/api/knowledge/conversations/{conversation_id}', status_code=204)
    def delete_conversation(conversation_id: int, request: Request, user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user)
            _owner(db, conversation_id, user)
            db.execute('DELETE FROM knowledge_conversations WHERE id=%s', (conversation_id,))
            authorize_locked(db, request, user)

    @app.post('/api/knowledge/conversations/{conversation_id}/turns', status_code=201)
    def ask(conversation_id: int, payload: Turn, request: Request, user: Annotated[User, Depends(authenticate)]):
        question = payload.question.strip()
        if not question:
            raise HTTPException(status_code=422, detail='Question is required')
        if payload.generate_answer and (os.environ.get('TAWZEEF_POSTGRES_ENABLE_GROQ') != '1'
                                        or not os.environ.get('GROQ_API_KEY', '').strip()):
            raise HTTPException(status_code=503, detail='External answer generation is not configured')
        hybrid_acquired = False
        acquired = False
        try:
            if payload.experimental_hybrid:
                directory = os.environ.get('TAWZEEF_EMBEDDING_MODEL_DIR', '')
                if os.environ.get('TAWZEEF_POSTGRES_KNOWLEDGE_HYBRID') != '1' or not directory:
                    raise HTTPException(status_code=503, detail='Experimental hybrid search is not configured')
                hybrid_acquired = knowledge._HYBRID_BUSY.acquire(blocking=False)
                if not hybrid_acquired:
                    raise HTTPException(status_code=429, detail='Experimental hybrid search is busy')
            if payload.generate_answer:
                acquired = knowledge._GENERATION_BUSY.acquire(blocking=False)
                if not acquired:
                    raise HTTPException(status_code=429, detail='External answer generation is busy')
            return save_turn(conversation_id, payload, request, user, question)
        finally:
            if acquired:
                knowledge._GENERATION_BUSY.release()
            if hybrid_acquired:
                knowledge._HYBRID_BUSY.release()

    def save_turn(conversation_id, payload, request, user, question):
        with connect() as db:
            authorize_locked(db, request, user)
            _owner(db, conversation_id, user)
            turns = db.execute('SELECT id,question FROM knowledge_conversation_turns WHERE conversation_id=%s ORDER BY id',
                               (conversation_id,)).fetchall()
            if len(turns) >= 100:
                raise HTTPException(status_code=409, detail='Conversation turn limit reached')
            previous_id = turns[-1]['id'] if turns else None
            previous_question = turns[-1]['question'] if turns else ''
            rows = _documents(db, user.role, payload.job_id, payload.section, payload.collection)
            sources, by_id = [], {}
            for row in rows:
                if payload.experimental_hybrid:
                    passages = _document_passages({'id': row['id'], 'title': row['title'], 'text': row['body']})
                    selected_sources = [Source(id=p.id, title=p.title, text=p.text, page=row['page']) for p in passages]
                else:
                    selected_sources = [Source(id=f"pg-doc-{row['id']}", title=row['title'], text=row['body'], page=row['page'])]
                sources.extend(selected_sources)
                by_id.update({source.id: row for source in selected_sources})
            ranked = _rank_lexical(_tokens(question), sources)
            lexical_match = bool(ranked)
            if not ranked and not payload.experimental_hybrid:
                ranked = _unique_policy_title(question, sources)
            semantic = []
            if payload.experimental_hybrid:
                try:
                    model = knowledge._load_embedder(os.environ['TAWZEEF_EMBEDDING_MODEL_DIR'])
                    semantic = knowledge._semantic_candidates(db, sources, question, model)
                except Exception as exc:
                    raise HTTPException(status_code=503, detail='Experimental hybrid search is unavailable') from exc
                ranked = knowledge._rerank_lexical_with_semantic(ranked, semantic)
            ranked = ranked[:3]
            ranked_ids = {source.id for _, source in ranked}
            suggestions = [source for _, source in semantic if source.id not in ranked_ids]
            def reference(source):
                ref = {'id': by_id[source.id]['id'], 'digest': _digest(by_id[source.id])}
                if payload.experimental_hybrid:
                    ref['passage_id'] = source.id
                return ref
            refs = [reference(source) for _, source in ranked]
            leads = [reference(source) for source in suggestions]
            authorize_locked(db, request, user)

        answer = None
        notice = 'Unverified excerpts from synthetic documents; no external service was called.'
        if payload.generate_answer and lexical_match:
            try:
                generated = knowledge.generate_with_groq(question, [
                    {'id': source.id, 'title': source.title, 'text': source.text[:4000]} for _, source in ranked
                ], previous_question=previous_question)
                generated = re.sub(r'【([^【】\[\]\n]{1,128})】', r'[\1]', generated)
                if '【' not in generated and '】' not in generated and knowledge._has_cited_sentences(generated, [s for _, s in ranked]):
                    answer = generated
                    notice = 'Generated using excerpts sent to Groq; verify all claims against the cited sources.'
                else:
                    notice = 'Generated citations could not be verified; showing unverified excerpts.'
            except ProviderUnavailable:
                notice = 'External generation was unavailable; the question and excerpts may have been sent. Showing unverified excerpts.'
        elif payload.generate_answer and ranked:
            notice = 'Only a title match was found; nothing was sent to Groq. Review the unverified source.'

        with connect() as db:
            authorize_locked(db, request, user)
            _owner(db, conversation_id, user)
            current_turns = db.execute('SELECT id FROM knowledge_conversation_turns WHERE conversation_id=%s ORDER BY id',
                                       (conversation_id,)).fetchall()
            if len(current_turns) != len(turns) or (current_turns[-1]['id'] if current_turns else None) != previous_id:
                raise HTTPException(status_code=409, detail='Conversation changed; review it before retrying')
            current_docs = {row['id']: row for row in _documents(db, user.role, payload.job_id, payload.section, payload.collection)}
            if any(ref['id'] not in current_docs or _digest(current_docs[ref['id']]) != ref['digest'] for ref in refs + leads):
                raise HTTPException(status_code=409, detail='A source changed; review it before retrying')
            row = db.execute('''INSERT INTO knowledge_conversation_turns(conversation_id,question,sources_json,generated_answer,suggestions_json,collection_filter)
                VALUES (%s,%s,%s,%s,%s,%s) RETURNING id,created_at''',
                (conversation_id, question, json.dumps(refs, separators=(',', ':')), answer,
                 json.dumps(leads, separators=(',', ':')), payload.collection)).fetchone()
            authorize_locked(db, request, user)
            return {'id': row['id'], 'created_at': row['created_at'], 'question': question,
                    'collection_filter': payload.collection,
                    'mode': 'groq' if answer else ('extractive' if refs else 'abstain'), 'answer': answer,
                    'sources': [source_dict(source, by_id) for _, source in ranked],
                    'suggestions': [source_dict(source, by_id) for source in suggestions],
                    'notice': notice}

    @app.get('/api/knowledge/conversations/{conversation_id}/turns')
    def read(conversation_id: int, request: Request, user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user)
            _owner(db, conversation_id, user)
            turns = db.execute('''SELECT id,question,sources_json,generated_answer,suggestions_json,collection_filter,created_at FROM knowledge_conversation_turns
                WHERE conversation_id=%s ORDER BY id LIMIT 100 FOR SHARE''', (conversation_id,)).fetchall()
            docs = {r['id']: r for r in _documents(db, user.role)}
            output = []
            for turn in turns:
                try:
                    refs = json.loads(turn['sources_json'])
                    if not isinstance(refs, list) or len(refs) > 3:
                        raise ValueError('Invalid references')
                    excerpts = [_reconstruct(ref, docs) for ref in refs]
                    available = all(excerpt is not None for excerpt in excerpts)
                except (TypeError, ValueError, KeyError):
                    available, excerpts = False, []
                excerpts = excerpts if available else []
                answer = turn['generated_answer'] if available and excerpts else None
                try:
                    leads = json.loads(turn['suggestions_json'])
                    if not isinstance(leads, list) or len(leads) > 3:
                        raise ValueError('Invalid suggestions')
                    suggestions = [_reconstruct(ref, docs) for ref in leads]
                    leads_available = all(suggestion is not None for suggestion in suggestions)
                except (TypeError, ValueError, KeyError):
                    leads_available, suggestions = False, []
                suggestions = suggestions if leads_available else []
                output.append({'id': turn['id'], 'question': turn['question'], 'created_at': turn['created_at'],
                               'collection_filter': turn['collection_filter'],
                               'mode': ('groq' if answer else ('extractive' if excerpts else 'abstain')) if available else 'source_unavailable',
                               'answer': answer,
                               'sources': excerpts, 'suggestions': suggestions, 'suggestions_unavailable': not leads_available})
            authorize_locked(db, request, user)
            return {'items': output, 'notice': 'Unverified excerpts from currently accessible synthetic documents.'}
