"""Explicit, single-attempt Google Calendar delivery for the synthetic PostgreSQL demo."""

import json
import re
import sys
import uuid
from datetime import UTC, datetime
from typing import Annotated

from fastapi import Depends, HTTPException, Request
from pydantic import BaseModel, ConfigDict, StrictBool

from app.auth import User

DDL = ('''CREATE TABLE IF NOT EXISTS pg_calendar_deliveries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interview_id bigint NOT NULL UNIQUE REFERENCES interviews(id),
    application_id bigint NOT NULL REFERENCES applications(id),
    candidate_id bigint NOT NULL REFERENCES users(id),
    start_at timestamptz NOT NULL, end_at timestamptz NOT NULL,
    event_id text NOT NULL UNIQUE, binding text, etag text,
    state text NOT NULL CHECK (state IN ('pending','sending','confirmed','rejected','uncertain','removing','removed','removal_uncertain')),
    created_by bigint NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp())''',
    'ALTER TABLE pg_calendar_deliveries ADD COLUMN IF NOT EXISTS context_changed boolean NOT NULL DEFAULT false')
_BINDING = re.compile(r'^[a-f0-9]{64}$')
_ETAG = re.compile(r'^"[^"\r\n]{1,256}"$')


class Confirm(BaseModel):
    model_config = ConfigDict(extra='forbid')
    confirmed: StrictBool
    event_id: str | None = None


def cancellation_blocked(db, interview_id):
    return bool(db.execute("""SELECT 1 FROM pg_calendar_deliveries WHERE interview_id=%s
        AND state IN ('sending','confirmed','uncertain','removing','removal_uncertain')""", (interview_id,)).fetchone())


def _review(db, interview_id):
    row = db.execute('''SELECT i.*,a.candidate_id AS app_candidate,a.status AS app_status,
        u.active,u.role FROM interviews i JOIN applications a ON a.id=i.application_id
        JOIN users u ON u.id=i.candidate_id WHERE i.id=%s FOR UPDATE OF i,a FOR SHARE OF u''', (interview_id,)).fetchone()
    if row is None:
        raise HTTPException(status_code=404, detail='Interview not found')
    if (row['candidate_id'] != row['app_candidate'] or row['app_status'] != 'advanced' or
            not row['active'] or row['role'] != 'candidate' or row['status'] != 'scheduled' or
            row['completed'] or row['start_at'] <= datetime.now(UTC) or row['end_at'] <= row['start_at']):
        raise HTTPException(status_code=409, detail='Interview is not eligible for calendar delivery')
    return row


def _same(draft, row):
    return all(draft[k] == row[k] for k in ('application_id', 'candidate_id', 'start_at', 'end_at'))


def _audit(db, row, actor, action):
    db.execute('INSERT INTO audit_events(application_id,actor_id,action,details) VALUES (%s,%s,%s,%s)',
               (row['application_id'], actor, action, json.dumps({'interview_id': row['interview_id']})))


def _public(row):
    return {k: row[k] for k in ('id', 'interview_id', 'application_id', 'start_at', 'end_at',
                                 'event_id', 'state', 'context_changed', 'created_at', 'updated_at')}


def install_routes(app, connect, authenticate, authorize_locked, guard):
    def authorized(db, request, user):
        authorize_locked(db, request, user, 'hr')

    def get(db, interview_id):
        row = db.execute('SELECT * FROM pg_calendar_deliveries WHERE interview_id=%s', (interview_id,)).fetchone()
        if row is None:
            raise HTTPException(status_code=404, detail='Calendar draft not found')
        return row

    @app.get('/api/google/interviews/{interview_id}/calendar')
    def view(interview_id: int, request: Request, user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorized(db, request, user)
            row = get(db, interview_id)
            authorized(db, request, user)
            return _public(row)

    @app.post('/api/google/interviews/{interview_id}/calendar', status_code=201)
    def prepare(interview_id: int, payload: Confirm, request: Request, user: Annotated[User, Depends(authenticate)]):
        if not payload.confirmed or payload.event_id is not None:
            raise HTTPException(status_code=422, detail='Confirm preparation without an event ID')
        with connect() as db:
            authorized(db, request, user)
            guard(db)
            interview = _review(db, interview_id)
            row = db.execute('SELECT * FROM pg_calendar_deliveries WHERE interview_id=%s', (interview_id,)).fetchone()
            if row:
                if row['state'] != 'pending' or not _same(row, interview):
                    raise HTTPException(status_code=409, detail='Calendar delivery needs separate review')
                authorized(db, request, user)
                return _public(row)
            row = db.execute('''INSERT INTO pg_calendar_deliveries
                (interview_id,application_id,candidate_id,start_at,end_at,event_id,state,created_by)
                VALUES (%s,%s,%s,%s,%s,%s,'pending',%s) RETURNING *''',
                (interview_id,interview['application_id'],interview['candidate_id'],interview['start_at'],
                 interview['end_at'],uuid.uuid4().hex,user.id)).fetchone()
            _audit(db, row, user.id, 'google_calendar_prepared')
            authorized(db, request, user)
            return _public(row)

    @app.post('/api/google/interviews/{interview_id}/calendar/send')
    def send(interview_id: int, payload: Confirm, request: Request, user: Annotated[User, Depends(authenticate)]):
        if not payload.confirmed or not payload.event_id:
            raise HTTPException(status_code=422, detail='Confirm the reviewed event ID')
        with connect() as db:
            authorized(db, request, user)
            row = get(db, interview_id)
            if row['state'] != 'pending' or row['event_id'] != payload.event_id:
                raise HTTPException(status_code=409, detail='Calendar draft changed or was already attempted')
        preflight = getattr(app.state, 'google_preflight', None)
        if not callable(preflight):
            raise HTTPException(status_code=503, detail='Google Calendar is not configured')
        try:
            dispatcher = preflight('calendar')
            binding = getattr(dispatcher, 'google_credential_binding', None)
            if not callable(dispatcher) or not isinstance(binding, str) or not _BINDING.fullmatch(binding):
                raise ValueError('Calendar identity unavailable')
        except Exception as exc:
            raise HTTPException(status_code=503, detail='Google Calendar authorization unavailable') from exc
        with connect() as db:
            authorized(db, request, user)
            guard(db)
            interview = _review(db, interview_id)
            row = get(db, interview_id)
            if row['state'] != 'pending' or row['event_id'] != payload.event_id or not _same(row, interview):
                raise HTTPException(status_code=409, detail='Calendar draft changed or was already attempted')
            db.execute("UPDATE pg_calendar_deliveries SET state='sending',binding=%s,updated_at=clock_timestamp() WHERE id=%s", (binding,row['id']))
            _audit(db, row, user.id, 'google_calendar_started')
            authorized(db, request, user)
        # The claim is durable before any provider call. Revalidate once more;
        # if this fails, the provider has not been contacted by this attempt.
        try:
            with connect() as db:
                authorized(db, request, user)
                guard(db)
                current = get(db, interview_id)
                if (current['state'] != 'sending' or current['event_id'] != row['event_id'] or
                        current['binding'] != binding or not _same(row, _review(db, interview_id))):
                    raise HTTPException(status_code=409, detail='Interview changed; review the calendar draft')
                authorized(db, request, user)
        except HTTPException:
            with connect() as db:
                db.execute("""UPDATE pg_calendar_deliveries SET state='rejected',updated_at=clock_timestamp()
                    WHERE id=%s AND state='sending' AND binding=%s AND event_id=%s""", (row['id'],binding,row['event_id']))
                _audit(db, row, user.id, 'google_calendar_preflight_rejected')
            raise
        try:
            result = dispatcher(kind='calendar', event_id=row['event_id'], start_at=row['start_at'].isoformat(),
                                end_at=row['end_at'].isoformat(), recipient=None)
            state = result.get('status') if isinstance(result, dict) else None
            etag = result.get('etag') if isinstance(result, dict) else None
            if state == 'confirmed' and (result.get('provider_id') != row['event_id'] or
                    not isinstance(etag, str) or not _ETAG.fullmatch(etag)):
                state = 'uncertain'
            if state not in ('confirmed', 'rejected', 'uncertain'):
                state = 'uncertain'
        except Exception:  # noqa: BLE001 - a provider error may follow a successful request.
            state, etag = 'uncertain', None
        with connect() as db:
            guard(db)
            try:
                changed = not _same(row, _review(db, interview_id))
            except HTTPException:
                changed = True
            db.execute('''UPDATE pg_calendar_deliveries SET state=%s,etag=%s,context_changed=%s,updated_at=clock_timestamp()
                WHERE id=%s AND state='sending' ''', (state, etag if state == 'confirmed' else None, changed, row['id']))
            _audit(db, row, user.id, 'google_calendar_result')
        with connect() as db:
            authorized(db, request, user)
            return _public(get(db, interview_id))

    @app.post('/api/google/interviews/{interview_id}/calendar/reconcile')
    def reconcile(interview_id: int, payload: Confirm, request: Request, user: Annotated[User, Depends(authenticate)]):
        """Only recover a terminal ambiguous result when our exact event exists."""
        if not payload.confirmed or not payload.event_id:
            raise HTTPException(status_code=422, detail='Confirm the reviewed event ID')
        with connect() as db:
            authorized(db, request, user)
            row = get(db, interview_id)
            if (row['state'] not in ('uncertain', 'removal_uncertain') or row['event_id'] != payload.event_id
                    or not isinstance(row['binding'], str) or not _BINDING.fullmatch(row['binding'])):
                raise HTTPException(status_code=409, detail='A terminal uncertain delivery is required')
            authorized(db, request, user)
        preflight = getattr(app.state, 'google_calendar_inspection_preflight', None)
        if not callable(preflight):
            raise HTTPException(status_code=503, detail='Calendar inspection is not configured')
        try:
            inspect = preflight()
            if not callable(inspect) or getattr(inspect, 'google_credential_binding', None) != row['binding']:
                raise ValueError('Calendar identity changed')
        except Exception as exc:
            raise HTTPException(status_code=503, detail='Original Google Calendar authorization unavailable') from exc
        with connect() as db:
            authorized(db, request, user)
            guard(db)
            current = get(db, interview_id)
            if any(current[k] != row[k] for k in ('state', 'event_id', 'binding', 'etag')):
                raise HTTPException(status_code=409, detail='Calendar delivery changed')
            authorized(db, request, user)
        try:
            result = inspect(event_id=row['event_id'], start=row['start_at'].isoformat(), end=row['end_at'].isoformat())
        except Exception:  # noqa: BLE001 - leave the durable outcome unchanged on any inspection failure.
            result = None
        etag = result.get('etag') if isinstance(result, dict) else None
        verified = (isinstance(result, dict) and result.get('status') == 'confirmed'
                    and result.get('event_id') == row['event_id'] and isinstance(etag, str)
                    and bool(_ETAG.fullmatch(etag))
                    and (row['state'] != 'removal_uncertain' or etag == row['etag']))
        with connect() as db:
            authorized(db, request, user)
            guard(db)
            current = get(db, interview_id)
            if any(current[k] != row[k] for k in ('state', 'event_id', 'binding', 'etag')):
                raise HTTPException(status_code=409, detail='Calendar delivery changed')
            if verified:
                db.execute("UPDATE pg_calendar_deliveries SET state='confirmed',etag=%s,updated_at=clock_timestamp() WHERE id=%s", (etag, row['id']))
                _audit(db, row, user.id, 'google_calendar_reconciled_existing')
            authorized(db, request, user)
            return _public(get(db, interview_id))

    @app.post('/api/google/interviews/{interview_id}/calendar/remove')
    def remove(interview_id: int, payload: Confirm, request: Request, user: Annotated[User, Depends(authenticate)]):
        if not payload.confirmed or not payload.event_id:
            raise HTTPException(status_code=422, detail='Confirm the reviewed event ID')
        with connect() as db:
            authorized(db, request, user)
            row = get(db, interview_id)
            if row['state'] != 'confirmed' or row['event_id'] != payload.event_id:
                raise HTTPException(status_code=409, detail='Confirmed calendar delivery required')
        preflight = getattr(app.state, 'google_calendar_removal_preflight', None)
        if not callable(preflight):
            raise HTTPException(status_code=503, detail='Calendar removal is not configured')
        try:
            remover = preflight()
            if not callable(remover) or getattr(remover, 'google_credential_binding', None) != row['binding']:
                raise ValueError('Calendar identity changed')
        except Exception as exc:
            raise HTTPException(status_code=503, detail='Original Google Calendar authorization unavailable') from exc
        with connect() as db:
            authorized(db, request, user)
            guard(db)
            current = get(db, interview_id)
            if current['state'] != 'confirmed' or current['event_id'] != payload.event_id or current['binding'] != row['binding'] or current['etag'] != row['etag']:
                raise HTTPException(status_code=409, detail='Calendar delivery changed')
            db.execute("UPDATE pg_calendar_deliveries SET state='removing',updated_at=clock_timestamp() WHERE id=%s", (row['id'],))
            _audit(db, row, user.id, 'google_calendar_removal_started')
            authorized(db, request, user)
        try:
            with connect() as db:
                authorized(db, request, user)
                guard(db)
                current = get(db, interview_id)
                if (current['state'] != 'removing' or current['event_id'] != row['event_id'] or
                        current['binding'] != row['binding'] or current['etag'] != row['etag']):
                    raise HTTPException(status_code=409, detail='Calendar delivery changed')
                authorized(db, request, user)
        except HTTPException:
            with connect() as db:
                db.execute("""UPDATE pg_calendar_deliveries SET state='confirmed',updated_at=clock_timestamp()
                    WHERE id=%s AND state='removing' AND binding=%s AND etag=%s AND event_id=%s""",
                    (row['id'],row['binding'],row['etag'],row['event_id']))
                _audit(db, row, user.id, 'google_calendar_removal_preflight_rejected')
            raise
        try:
            result = remover(event_id=row['event_id'], etag=row['etag'], start=row['start_at'].isoformat(), end=row['end_at'].isoformat())
            state = 'removed' if isinstance(result, dict) and result.get('status') == 'removed' else 'removal_uncertain'
        except Exception:  # noqa: BLE001 - removal could have succeeded before a connection failure.
            state = 'removal_uncertain'
        with connect() as db:
            db.execute("UPDATE pg_calendar_deliveries SET state=%s,updated_at=clock_timestamp() WHERE id=%s AND state='removing'", (state,row['id']))
            _audit(db, row, user.id, 'google_calendar_removal_result')
        with connect() as db:
            authorized(db, request, user)
            return _public(get(db, interview_id))


def configure(app):
    if sys.platform != 'win32':
        raise RuntimeError('Google local integration requires Windows Credential Manager')
    from app.google_dispatch import (
        prepare_calendar_inspection,
        prepare_calendar_removal,
        prepare_dispatch,
    )
    app.state.google_preflight = prepare_dispatch
    app.state.google_calendar_removal_preflight = prepare_calendar_removal
    app.state.google_calendar_inspection_preflight = prepare_calendar_inspection
