class Advance(BaseModel):
    decision: str
    note: str = ''
    rubric_event_id: StrictInt | None = Field(default=None, gt=0)


def install_routes(app, connect, authenticate, authorize_locked):
    """Install only local, explicit HR/candidate actions in this demo mode."""
    def guard(db):
        # All scheduling writes take this lock before querying availability.
        db.execute("SELECT pg_advisory_xact_lock(hashtext(current_schema()), hashtext('tawzeef-scheduling-v1'))")

    def owner(db, application_id, user):
        row = db.execute('SELECT * FROM applications WHERE id=%s AND candidate_id=%s FOR UPDATE',
                         (application_id, user.id)).fetchone()
        if row is None:
            raise HTTPException(status_code=404, detail='Application not found')
        if row['status'] != 'advanced':
            raise HTTPException(status_code=409, detail='Application is not eligible for booking')
        return row

    @app.post('/api/applications/{application_id}/decision')
    def advance(application_id: int, payload: Advance, request: Request,
                user: Annotated[User, Depends(authenticate)]):
        if user.role != 'hr':
            raise HTTPException(status_code=403, detail='Access denied')
        if (payload.decision not in {'advance', 'hire', 'reject'} or len(payload.note) > 2000
                or (payload.rubric_event_id is not None and payload.decision != 'advance')
                or (payload.decision == 'reject' and not payload.note.strip())):
            raise HTTPException(status_code=422, detail='Invalid decision or missing rejection reason')
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            guard(db)
            if payload.decision == 'hire':
                result = application_view(hire(db, application_id, user, payload.note), user)
                authorize_locked(db, request, user, 'hr')
                return result
            row = db.execute('SELECT * FROM applications WHERE id=%s FOR UPDATE', (application_id,)).fetchone()
            if not row:
                raise HTTPException(status_code=404, detail='Application not found')
            if payload.decision == 'reject':
                if row['status'] not in ('submitted', 'advanced', 'offered'):
                    raise HTTPException(status_code=409, detail='Decision is not allowed from current status')
                if db.execute("SELECT 1 FROM job_offers WHERE application_id=%s AND status='accepted'", (application_id,)).fetchone():
                    raise HTTPException(status_code=409, detail='An accepted offer must be resolved before rejection')
                offer = db.execute("UPDATE job_offers SET status='withdrawn',responded_at=clock_timestamp() WHERE application_id=%s AND status='presented' RETURNING id", (application_id,)).fetchone()
                if offer:
                    db.execute("INSERT INTO audit_events(application_id,actor_id,action,details) VALUES (%s,%s,'offer_withdrawn',%s)",
                               (application_id, user.id, json.dumps({'offer_id': offer['id']})))
                interviews = db.execute("SELECT id,candidate_id FROM interviews WHERE application_id=%s AND status='scheduled' AND start_at>clock_timestamp() FOR UPDATE", (application_id,)).fetchall()
                for interview in interviews:
                    if interview['candidate_id'] != row['candidate_id']:
                        raise HTTPException(status_code=409, detail='Interview ownership changed')
                    db.execute("UPDATE interviews SET status='cancelled' WHERE id=%s", (interview['id'],))
                    db.execute('INSERT INTO hr_interview_cancellations(interview_id,candidate_id) VALUES (%s,%s)', (interview['id'], row['candidate_id']))
                    db.execute("INSERT INTO audit_events(application_id,actor_id,action,details) VALUES (%s,%s,'interview_cancelled',%s)",
                               (application_id, user.id, json.dumps({'interview_id': interview['id'], 'reason': 'application_rejected'})))
                db.execute("UPDATE applications SET status='rejected', updated_at=to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"') WHERE id=%s", (application_id,))
                db.execute("INSERT INTO audit_events(application_id,actor_id,action,details) VALUES (%s,%s,'decision',%s)",
                           (application_id, user.id, json.dumps({'decision': 'reject', 'note': payload.note.strip()}, ensure_ascii=False)))
                result = application_view(db.execute('SELECT * FROM applications WHERE id=%s', (application_id,)).fetchone(), user)
                authorize_locked(db, request, user, 'hr')
                return result
            if row['status'] != 'submitted':
                raise HTTPException(status_code=409, detail='A submitted, screened application is required')
            if payload.rubric_event_id is not None:
                _, _, current_digest = rubric_source(db, application_id)
                review = db.execute('''SELECT h.source_digest,h.review_json,e.details,e.action,e.actor_id,h.reviewer_id,
                    e.application_id AS audit_application
                    FROM hr_rubric_history h JOIN audit_events e ON e.id=h.audit_event_id
                    JOIN hr_rubric_assessments a ON a.application_id=h.application_id
                    WHERE h.application_id=%s AND h.audit_event_id=%s
                    AND h.source_digest=a.source_digest AND h.review_json=a.review_json AND h.reviewer_id=a.reviewer_id
                    AND h.audit_event_id=(SELECT max(audit_event_id) FROM hr_rubric_history WHERE application_id=%s)
                    FOR SHARE OF h,e,a''', (application_id, payload.rubric_event_id, application_id)).fetchone()
                try:
                    details = json.loads(review['details']) if review else None
                    content = json.loads(review['review_json']) if review else None
                    valid = (review and review['source_digest'] == current_digest and
                             review['action'] == 'rubric_reviewed' and review['actor_id'] == review['reviewer_id'] and
                             review['audit_application'] == application_id and
                             details.get('source_digest') == current_digest and
                             details.get('review_digest') == hashlib.sha256(review['review_json'].encode()).hexdigest() and
                             any(item.get('score') is not None for item in content['items']))
                except (TypeError, ValueError, KeyError, AttributeError):
                    valid = False
                if not valid:
                    raise HTTPException(status_code=409, detail='Current reviewed rubric assessment required')
            elif row['score_json'] is None or not db.execute('''SELECT 1 FROM screening_history h JOIN audit_events e ON e.id=h.audit_event_id
                WHERE e.application_id=%s AND e.action='screened' AND h.score_json=%s LIMIT 1''',
                              (application_id, row['score_json'])).fetchone():
                raise HTTPException(status_code=409, detail='A recorded screening is required')
            if not db.execute("SELECT 1 FROM users WHERE id=%s AND active=1 AND role='candidate' FOR SHARE", (row['candidate_id'],)).fetchone():
                raise HTTPException(status_code=409, detail='An active candidate is required')
            db.execute("UPDATE applications SET status='advanced', updated_at=to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"') WHERE id=%s", (application_id,))
            db.execute("INSERT INTO audit_events(application_id,actor_id,action,details) VALUES (%s,%s,'decision',%s)",
                       (application_id, user.id, json.dumps({'decision': 'advance', 'note': payload.note,
                        **({'rubric_event_id': payload.rubric_event_id} if payload.rubric_event_id is not None else {})}, ensure_ascii=False)))
            result = application_view(db.execute('SELECT * FROM applications WHERE id=%s', (application_id,)).fetchone(), user)
            authorize_locked(db, request, user, 'hr')
            return result

    install_offer_routes(app, connect, authenticate, authorize_locked, guard)

    @app.post('/api/slots', status_code=201)
    def create_slot(payload: SlotCreate, request: Request, user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            guard(db)
            if payload.start_at <= datetime.now(UTC):
                raise HTTPException(status_code=422, detail='Slot must start in the future')
            key = payload.interviewer.casefold()
            if db.execute('''SELECT 1 FROM interview_slots WHERE interviewer_key=%s
                AND start_at < %s AND end_at > %s LIMIT 1''', (key, payload.end_at, payload.start_at)).fetchone():
                raise HTTPException(status_code=409, detail='Interviewer slot conflict')
            row = db.execute('''INSERT INTO interview_slots(start_at,end_at,interviewer,interviewer_key,created_by)
                VALUES (%s,%s,%s,%s,%s) RETURNING id,start_at,end_at,interviewer''',
                (payload.start_at, payload.end_at, payload.interviewer, key, user.id)).fetchone()
            db.execute("INSERT INTO slot_audit_events(slot_id,actor_id,action) VALUES (%s,%s,'created')", (row['id'], user.id))
            authorize_locked(db, request, user, 'hr')
            return dict(row)

    @app.get('/api/slots')
    def list_slots(request: Request, user: Annotated[User, Depends(authenticate)], application_id: int):
        with connect() as db:
            authorize_locked(db, request, user, 'candidate')
            application = owner(db, application_id, user)
            if db.execute("SELECT 1 FROM interviews WHERE application_id=%s AND status='scheduled' AND NOT completed", (application_id,)).fetchone():
                authorize_locked(db, request, user, 'candidate')
                return []
            rows = db.execute('''SELECT s.id,s.start_at,s.end_at,s.interviewer FROM interview_slots s
                WHERE s.start_at > clock_timestamp() AND NOT EXISTS (SELECT 1 FROM interviews i WHERE i.status='scheduled'
                  AND i.start_at < s.end_at AND i.end_at > s.start_at
                  AND (i.slot_id=s.id OR i.candidate_id=%s OR i.interviewer_key=s.interviewer_key))
                ORDER BY s.start_at,s.id LIMIT 100''', (application['candidate_id'],)).fetchall()
            authorize_locked(db, request, user, 'candidate')
            return [dict(row) for row in rows]

    @app.get('/api/interviews')
    def list_interviews(request: Request, user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user)
            fields = 'id,application_id,candidate_id,start_at,end_at,interviewer,status,completed'
            if user.role == 'candidate':
                rows = db.execute(f'SELECT {fields} FROM interviews WHERE candidate_id=%s ORDER BY start_at,id',
                                  (user.id,)).fetchall()
            elif user.role == 'hr':
                rows = db.execute(f'SELECT {fields} FROM interviews ORDER BY start_at,id').fetchall()
            else:
                raise HTTPException(status_code=403, detail='Access denied')
            authorize_locked(db, request, user)
            return [dict(row) for row in rows]

    @app.post('/api/interviews/{interview_id}/complete')
    def complete_interview(interview_id: int, request: Request, user: Annotated[User, Depends(authenticate)]):
        """Record HR's confirmation that an ended interview took place."""
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            guard(db)
            row = db.execute('''SELECT i.*, a.candidate_id AS application_candidate_id,
                a.status AS application_status FROM interviews i
                JOIN applications a ON a.id=i.application_id WHERE i.id=%s FOR UPDATE OF i,a''',
                (interview_id,)).fetchone()
            if row is None:
                raise HTTPException(status_code=404, detail='Interview not found')
            if (row['status'] != 'scheduled' or row['completed'] or row['end_at'] > datetime.now(UTC)
                    or row['application_status'] != 'advanced'
                    or row['candidate_id'] != row['application_candidate_id']):
                raise HTTPException(status_code=409, detail='Interview cannot be marked completed')
            updated = db.execute('''UPDATE interviews SET completed=true WHERE id=%s
                RETURNING id,application_id,candidate_id,start_at,end_at,interviewer,status,completed''',
                (interview_id,)).fetchone()
            db.execute("INSERT INTO audit_events(application_id,actor_id,action,details) VALUES (%s,%s,'interview_completed',%s)",
                       (row['application_id'], user.id, json.dumps({'interview_id': interview_id})))
            authorize_locked(db, request, user, 'hr')
            return dict(updated)

    def cancel(db, interview_id, user, by_candidate):
        guard(db)
        row = db.execute('''SELECT i.id,i.application_id,i.candidate_id,i.start_at,i.status,i.completed,
            a.candidate_id AS application_candidate_id,a.status AS application_status
            FROM interviews i JOIN applications a ON a.id=i.application_id
            WHERE i.id=%s FOR UPDATE OF i,a''', (interview_id,)).fetchone()
        if (row is None or (by_candidate and
                (row['candidate_id'] != user.id or row['application_candidate_id'] != user.id))):
            raise HTTPException(status_code=404, detail='Interview not found')
        if row['candidate_id'] != row['application_candidate_id']:
            raise HTTPException(status_code=409, detail='Interview ownership changed')
        if (row['status'] != 'scheduled' or row['completed'] or row['start_at'] <= datetime.now(UTC)
                or (by_candidate and row['application_status'] != 'advanced')):
            raise HTTPException(status_code=409, detail='Interview cannot be cancelled')
        updated = db.execute('''UPDATE interviews SET status='cancelled' WHERE id=%s
            RETURNING id,application_id,candidate_id,start_at,end_at,interviewer,status,completed''', (interview_id,)).fetchone()
        table = 'candidate_interview_cancellations' if by_candidate else 'hr_interview_cancellations'
        # table is a constant selected internally, never user input.
        db.execute(f'INSERT INTO {table}(interview_id,candidate_id) VALUES (%s,%s)',
                   (interview_id, row['candidate_id']))
        reason = 'candidate_cancelled' if by_candidate else 'hr_cancelled'
        db.execute("INSERT INTO audit_events(application_id,actor_id,action,details) VALUES (%s,%s,'interview_cancelled',%s)",
                   (row['application_id'], user.id, json.dumps({'interview_id': interview_id, 'reason': reason})))
        return dict(updated)

