class Advance(BaseModel):
    decision: str
    note: str = ''


def install_routes(app, connect, authenticate, authorize_locked):
    """Install only local, explicit HR/candidate actions in this demo mode."""
    def guard(db):
        # All scheduling writes take this lock before querying availability.
        db.execute("SELECT pg_advisory_xact_lock(hashtext(current_schema()), hashtext('tawzeef-scheduling-v1'))")

    def owner(db, application_id, user):
        row = db.execute('SELECT * FROM applications WHERE id=%s AND candidate_id=%s FOR UPDATE',
                         (application_id, user.id)).fetchone()
        if row is None:
            raise HTTPException(status_code=404, detail='Application not found')
        if row['status'] != 'advanced':
            raise HTTPException(status_code=409, detail='Application is not eligible for booking')
        return row

    @app.post('/api/applications/{application_id}/decision')
    def advance(application_id: int, payload: Advance, request: Request,
                user: Annotated[User, Depends(authenticate)]):
        if user.role != 'hr':
            raise HTTPException(status_code=403, detail='Access denied')
        if payload.decision != 'advance' or len(payload.note) > 2000:
            raise HTTPException(status_code=422, detail='Only advance is available in this mode')
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            guard(db)
            row = db.execute('SELECT * FROM applications WHERE id=%s FOR UPDATE', (application_id,)).fetchone()
            if not row:
                raise HTTPException(status_code=404, detail='Application not found')
            if row['status'] != 'submitted' or row['score_json'] is None:
                raise HTTPException(status_code=409, detail='A submitted, screened application is required')
            if not db.execute('''SELECT 1 FROM screening_history h JOIN audit_events e ON e.id=h.audit_event_id
                WHERE e.application_id=%s AND e.action='screened' AND h.score_json=%s LIMIT 1''',
                              (application_id, row['score_json'])).fetchone():
                raise HTTPException(status_code=409, detail='A recorded screening is required')
            if not db.execute("SELECT 1 FROM users WHERE id=%s AND active=1 AND role='candidate' FOR SHARE", (row['candidate_id'],)).fetchone():
                raise HTTPException(status_code=409, detail='An active candidate is required')
            db.execute("UPDATE applications SET status='advanced', updated_at=to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"') WHERE id=%s", (application_id,))
            db.execute("INSERT INTO audit_events(application_id,actor_id,action,details) VALUES (%s,%s,'decision',%s)",
                       (application_id, user.id, json.dumps({'decision': 'advance', 'note': payload.note}, ensure_ascii=False)))
            result = application_view(db.execute('SELECT * FROM applications WHERE id=%s', (application_id,)).fetchone(), user)
            authorize_locked(db, request, user, 'hr')
            return result

    @app.post('/api/slots', status_code=201)
    def create_slot(payload: SlotCreate, request: Request, user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            guard(db)
            if payload.start_at <= datetime.now(UTC):
                raise HTTPException(status_code=422, detail='Slot must start in the future')
            key = payload.interviewer.casefold()
            if db.execute('''SELECT 1 FROM interview_slots WHERE interviewer_key=%s
                AND start_at < %s AND end_at > %s LIMIT 1''', (key, payload.end_at, payload.start_at)).fetchone():
                raise HTTPException(status_code=409, detail='Interviewer slot conflict')
            row = db.execute('''INSERT INTO interview_slots(start_at,end_at,interviewer,interviewer_key,created_by)
                VALUES (%s,%s,%s,%s,%s) RETURNING id,start_at,end_at,interviewer''',
                (payload.start_at, payload.end_at, payload.interviewer, key, user.id)).fetchone()
            db.execute("INSERT INTO slot_audit_events(slot_id,actor_id,action) VALUES (%s,%s,'created')", (row['id'], user.id))
            authorize_locked(db, request, user, 'hr')
            return dict(row)

    @app.get('/api/slots')
    def list_slots(request: Request, user: Annotated[User, Depends(authenticate)], application_id: int):
        with connect() as db:
            authorize_locked(db, request, user, 'candidate')
            application = owner(db, application_id, user)
            if db.execute("SELECT 1 FROM interviews WHERE application_id=%s AND status='scheduled'", (application_id,)).fetchone():
                authorize_locked(db, request, user, 'candidate')
                return []
            rows = db.execute('''SELECT s.id,s.start_at,s.end_at,s.interviewer FROM interview_slots s
                WHERE s.start_at > now() AND NOT EXISTS (SELECT 1 FROM interviews i WHERE i.status='scheduled'
                  AND i.start_at < s.end_at AND i.end_at > s.start_at
                  AND (i.slot_id=s.id OR i.candidate_id=%s OR i.interviewer_key=s.interviewer_key))
                ORDER BY s.start_at,s.id LIMIT 100''', (application['candidate_id'],)).fetchall()
            authorize_locked(db, request, user, 'candidate')
            return [dict(row) for row in rows]

    @app.post('/api/slots/{slot_id}/book', status_code=201)
    def book(slot_id: int, payload: BookSlot, request: Request, user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user, 'candidate')
            guard(db)
            application = owner(db, payload.application_id, user)
            slot = db.execute('SELECT * FROM interview_slots WHERE id=%s', (slot_id,)).fetchone()
            if slot is None:
                raise HTTPException(status_code=404, detail='Slot not found')
            if slot['start_at'] <= datetime.now(UTC):
                raise HTTPException(status_code=409, detail='Slot is not available')
            if db.execute('''SELECT 1 FROM interviews WHERE status='scheduled' AND
                (application_id=%s OR slot_id=%s OR
                 (start_at < %s AND end_at > %s AND (candidate_id=%s OR interviewer_key=%s))) LIMIT 1''',
                (application['id'], slot_id, slot['end_at'], slot['start_at'], user.id, slot['interviewer_key'])).fetchone():
                raise HTTPException(status_code=409, detail='Interview or slot conflict')
            row = db.execute('''INSERT INTO interviews(slot_id,application_id,candidate_id,start_at,end_at,interviewer,interviewer_key,status,created_by)
                VALUES (%s,%s,%s,%s,%s,%s,%s,'scheduled',%s) RETURNING id,application_id,candidate_id,start_at,end_at,interviewer,status''',
                (slot_id,application['id'],user.id,slot['start_at'],slot['end_at'],slot['interviewer'],slot['interviewer_key'],user.id)).fetchone()
            db.execute('INSERT INTO candidate_interview_bookings(interview_id,candidate_id) VALUES (%s,%s)', (row['id'], user.id))
            db.execute("INSERT INTO audit_events(application_id,actor_id,action,details) VALUES (%s,%s,'interview_scheduled',%s)",
                       (application['id'],user.id,json.dumps({'interview_id': row['id'], 'slot_id': slot_id, 'source':'candidate_selection'})))
            authorize_locked(db, request, user, 'candidate')
            return dict(row)
