_EMAIL = re.compile(r'^[A-Za-z0-9][A-Za-z0-9._+-]{0,63}@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+$')


class Prepare(BaseModel):
    model_config = ConfigDict(extra='forbid')
    recipient: str = Field(max_length=254)
    confirmed: StrictBool


class Send(BaseModel):
    model_config = ConfigDict(extra='forbid')
    recipient: str = Field(max_length=254)
    delivery_id: int = Field(gt=0, strict=True)
    generation: int | None = Field(default=None, ge=0, strict=True)
    confirmed: StrictBool


class Revise(BaseModel):
    model_config = ConfigDict(extra='forbid')
    delivery_id: int = Field(gt=0, strict=True)
    expected_generation: int = Field(ge=0, strict=True)
    recipient: str = Field(max_length=254)
    confirmed: StrictBool


class Investigation(BaseModel):
    model_config = ConfigDict(extra='forbid')
    delivery_id: int = Field(gt=0, strict=True)
    expected_generation: int = Field(ge=0, strict=True)
    expected_state: Literal['sending', 'uncertain']
    observation: Literal['investigating', 'reported_message_found', 'reported_message_not_found', 'escalated']
    confirmed: StrictBool


def _generation_matches(row, generation):
    # Pre-generation clients work only for untouched original drafts.
    return row['generation'] == (0 if generation is None else generation)


def cancellation_blocked(db, interview_id):
    return bool(db.execute("""SELECT 1 FROM pg_email_deliveries WHERE interview_id=%s
        AND state IN ('sending','uncertain')""", (interview_id,)).fetchone())


def confirmation_sent(db, interview_id):
    return bool(db.execute("SELECT 1 FROM pg_email_deliveries WHERE interview_id=%s AND state='confirmed'",
                           (interview_id,)).fetchone())


def _audit(db, row, actor, action):
    db.execute('INSERT INTO audit_events(application_id,actor_id,action,details) VALUES (%s,%s,%s,%s)',
               (row['application_id'], actor, action, json.dumps({'interview_id': row['interview_id']})))


def _public(row):
    return {key: row[key] for key in ('id', 'interview_id', 'application_id', 'start_at', 'end_at',
        'recipient', 'subject', 'body', 'state', 'generation', 'context_changed', 'created_at', 'updated_at')}


def install_routes(app, connect, authenticate, authorize_locked, guard):
    def authorized(db, request, user):
        authorize_locked(db, request, user, 'hr')

    def get(db, interview_id):
        row = db.execute('SELECT * FROM pg_email_deliveries WHERE interview_id=%s', (interview_id,)).fetchone()
        if row is None:
            raise HTTPException(status_code=404, detail='Email draft not found')
        return row

    @app.get('/api/google/interviews/{interview_id}/email')
    def view(interview_id: int, request: Request, user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorized(db, request, user)
            row = get(db, interview_id)
            authorized(db, request, user)
            return _public(row)

    @app.post('/api/google/interviews/{interview_id}/email', status_code=201)
    def prepare(interview_id: int, payload: Prepare, request: Request, user: Annotated[User, Depends(authenticate)]):
        if not payload.confirmed or not _EMAIL.fullmatch(payload.recipient):
            raise HTTPException(status_code=422, detail='Confirm one valid, independently verified recipient')
        with connect() as db:
            authorized(db, request, user)
            guard(db)
            interview = _review(db, interview_id)
            row = db.execute('SELECT * FROM pg_email_deliveries WHERE interview_id=%s', (interview_id,)).fetchone()
            if row:
                if row['state'] != 'pending' or row['recipient'] != payload.recipient or not _same(row, interview):
                    raise HTTPException(status_code=409, detail='Email delivery needs separate review')
                authorized(db, request, user)
                return _public(row)
            subject, body = confirmation_content(interview['start_at'].isoformat(), interview['end_at'].isoformat())
            row = db.execute('''INSERT INTO pg_email_deliveries
                (interview_id,application_id,candidate_id,start_at,end_at,recipient,subject,body,state,created_by)
                VALUES (%s,%s,%s,%s,%s,%s,%s,%s,'pending',%s) RETURNING *''',
                (interview_id, interview['application_id'], interview['candidate_id'], interview['start_at'],
                 interview['end_at'], payload.recipient, subject, body, user.id)).fetchone()
            _audit(db, row, user.id, 'google_email_prepared')
            authorized(db, request, user)
            return _public(row)

    @app.post('/api/google/interviews/{interview_id}/email/revise')
    def revise(interview_id: int, payload: Revise, request: Request, user: Annotated[User, Depends(authenticate)]):
        if not payload.confirmed or not _EMAIL.fullmatch(payload.recipient):
            raise HTTPException(status_code=422, detail='Confirm one valid, independently verified recipient')
        with connect() as db:
            authorized(db, request, user)
            guard(db)
            interview = _review(db, interview_id)
            row = get(db, interview_id)
            if (row['id'] != payload.delivery_id or row['generation'] != payload.expected_generation
                    or row['state'] not in ('pending', 'rejected')):
                raise HTTPException(status_code=409, detail='Email draft changed or cannot be revised')
            if not _same(row, interview):
                raise HTTPException(status_code=409, detail='Interview changed; this draft cannot be revised')
            db.execute('''INSERT INTO pg_email_revisions
                (delivery_id,generation,state,recipient,start_at,end_at,subject,body,reviewed_by)
                VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s)''',
                (row['id'], row['generation'], row['state'], row['recipient'], row['start_at'], row['end_at'],
                 row['subject'], row['body'], user.id))
            subject, body = confirmation_content(interview['start_at'].isoformat(), interview['end_at'].isoformat())
            updated = db.execute('''UPDATE pg_email_deliveries SET recipient=%s,subject=%s,body=%s,
                state='pending',provider_id=NULL,context_changed=false,generation=generation+1,
                updated_at=clock_timestamp() WHERE id=%s AND generation=%s AND state IN ('pending','rejected') RETURNING *''',
                (payload.recipient,subject,body,row['id'],row['generation'])).fetchone()
            if not updated:
                raise HTTPException(status_code=409, detail='Email draft changed')
            _audit(db, row, user.id, 'google_email_revised')
            authorized(db, request, user)
            return _public(updated)

    @app.get('/api/google/interviews/{interview_id}/email/investigation')
    def investigation(interview_id: int, request: Request, user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorized(db, request, user)
            row = get(db, interview_id)
            events = db.execute('''SELECT id,generation,observed_state,observation,actor_id,created_at
                FROM pg_email_investigation_events WHERE delivery_id=%s ORDER BY id DESC LIMIT 100''',
                (row['id'],)).fetchall()
            authorized(db, request, user)
            return {'delivery_id': row['id'], 'generation': row['generation'], 'state': row['state'],
                    'events': events,
                    'notice': 'Operator reports are unverified and do not establish delivery or permit retry.'}

    @app.post('/api/google/interviews/{interview_id}/email/investigation', status_code=201)
    def record_investigation(interview_id: int, payload: Investigation, request: Request,
                             user: Annotated[User, Depends(authenticate)]):
        if not payload.confirmed:
            raise HTTPException(status_code=422, detail='Explicit confirmation is required')
        with connect() as db:
            authorized(db, request, user)
            guard(db)
            row = get(db, interview_id)
            if (row['id'] != payload.delivery_id or row['generation'] != payload.expected_generation
                    or row['state'] != payload.expected_state):
                raise HTTPException(status_code=409, detail='Delivery changed; check status again')
            count = db.execute('''SELECT count(*) AS count FROM pg_email_investigation_events
                WHERE delivery_id=%s AND generation=%s''', (row['id'], row['generation'])).fetchone()['count']
            if count >= 100:
                raise HTTPException(status_code=409, detail='Investigation event limit reached')
            event = db.execute('''INSERT INTO pg_email_investigation_events
                (delivery_id,generation,observed_state,observation,actor_id)
                VALUES (%s,%s,%s,%s,%s) RETURNING id,generation,observed_state,observation,actor_id,created_at''',
                (row['id'], row['generation'], row['state'], payload.observation, user.id)).fetchone()
            _audit(db, row, user.id, 'google_email_investigation_recorded')
            authorized(db, request, user)
            return {'event': event, 'state': row['state'],
                    'notice': 'This unverified operator report does not establish delivery or permit retry.'}

    @app.post('/api/google/interviews/{interview_id}/email/send')
    def send(interview_id: int, payload: Send, request: Request, user: Annotated[User, Depends(authenticate)]):
        if not payload.confirmed:
            raise HTTPException(status_code=422, detail='Explicit confirmation is required')
        with connect() as db:
            authorized(db, request, user)
            row = get(db, interview_id)
            if (row['state'] != 'pending' or row['id'] != payload.delivery_id or row['recipient'] != payload.recipient
                    or not _generation_matches(row, payload.generation)):
                raise HTTPException(status_code=409, detail='Email draft changed or was already attempted')
            authorized(db, request, user)
        preflight = getattr(app.state, 'google_email_preflight', None)
        if not callable(preflight):
            raise HTTPException(status_code=503, detail='Gmail is not configured')
        try:
            dispatcher = preflight('email')
            if not callable(dispatcher):
                raise TypeError('Gmail authorization unavailable')
        except Exception as exc:
            raise HTTPException(status_code=503, detail='Gmail authorization unavailable') from exc
        with connect() as db:
            authorized(db, request, user)
            guard(db)
            interview = _review(db, interview_id)
            row = get(db, interview_id)
            text = confirmation_content(row['start_at'].isoformat(), row['end_at'].isoformat())
            if (row['state'] != 'pending' or row['id'] != payload.delivery_id or row['recipient'] != payload.recipient
                    or not _generation_matches(row, payload.generation)
                    or not _same(row, interview) or text != (row['subject'], row['body'])):
                raise HTTPException(status_code=409, detail='Email draft or interview changed; review again')
            db.execute("UPDATE pg_email_deliveries SET state='sending',updated_at=clock_timestamp() WHERE id=%s", (row['id'],))
            _audit(db, row, user.id, 'google_email_started')
            authorized(db, request, user)
        try:
            with connect() as db:
                authorized(db, request, user)
                guard(db)
                current = get(db, interview_id)
                if (current['state'] != 'sending' or current['id'] != row['id'] or current['recipient'] != row['recipient']
                        or current['generation'] != row['generation']
                        or not _same(row, _review(db, interview_id))):
                    raise HTTPException(status_code=409, detail='Interview changed; review the email')
                authorized(db, request, user)
        except HTTPException:
            with connect() as db:
                db.execute("UPDATE pg_email_deliveries SET state='rejected',updated_at=clock_timestamp() WHERE id=%s AND state='sending'", (row['id'],))
                _audit(db, row, user.id, 'google_email_preflight_rejected')
            raise
        try:
            result = dispatcher(kind='email', event_id=None, start_at=row['start_at'].isoformat(),
                                end_at=row['end_at'].isoformat(), recipient=row['recipient'])
            state = result.get('status') if isinstance(result, dict) else None
            provider_id = result.get('provider_id') if isinstance(result, dict) else None
            if state == 'confirmed' and (not isinstance(provider_id, str) or not provider_id or len(provider_id) > 1024):
                state = 'uncertain'
            if state not in ('confirmed', 'rejected', 'uncertain'):
                state = 'uncertain'
        except Exception:  # noqa: BLE001 - a provider error may follow a successful send.
            state, provider_id = 'uncertain', None
        with connect() as db:
            guard(db)
            try:
                changed = not _same(row, _review(db, interview_id))
            except HTTPException:
                changed = True
            db.execute('''UPDATE pg_email_deliveries SET state=%s,provider_id=%s,context_changed=%s,
                updated_at=clock_timestamp() WHERE id=%s AND state='sending' ''',
                (state, provider_id if state == 'confirmed' else None, changed, row['id']))
            _audit(db, row, user.id, 'google_email_result')
        with connect() as db:
            authorized(db, request, user)
            return _public(get(db, interview_id))
