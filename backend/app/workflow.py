"""A persisted, human-supervised recruitment workflow for the local demo.

The plan is deterministic: it is not generated by an LLM. Running a plan can
screen a resume; hiring decisions and interview scheduling remain HR actions.
"""

import json
from pathlib import Path
from typing import Annotated

from fastapi import APIRouter, Depends, HTTPException, Request

from app.auth import User, require_roles
from app.db import connect
from app.recruitment import get_application, job_data, score_resume

router = APIRouter(prefix="/api/workflows")
HR = Annotated[User, Depends(require_roles("hr"))]


def initialize_workflows(path: str | Path) -> None:
    with connect(path) as db:
        db.execute("""CREATE TABLE IF NOT EXISTS recruitment_workflows (
            application_id INTEGER PRIMARY KEY REFERENCES applications(id),
            last_step TEXT NOT NULL,
            updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
        )""")


def describe(db, application) -> dict:
    interview = db.execute(
        "SELECT id, start_at FROM interviews WHERE application_id = ? AND status = 'scheduled' ORDER BY start_at DESC LIMIT 1",
        (application["id"],),
    ).fetchone()
    screened = application["score_json"] is not None
    status = application["status"]
    if status in {"hired", "rejected"}:
        next_step = "complete"
    elif not screened:
        next_step = "screen"
    elif status == "submitted":
        next_step = "human_review"
    elif not interview:
        next_step = "schedule_interview"
    else:
        next_step = "human_decision"
    saved = db.execute(
        "SELECT last_step, updated_at FROM recruitment_workflows WHERE application_id = ?",
        (application["id"],),
    ).fetchone()
    return {
        "application_id": application["id"],
        "status": status,
        "screened": screened,
        "interview": dict(interview) if interview else None,
        "next_step": next_step,
        "last_step": saved["last_step"] if saved else None,
        "updated_at": saved["updated_at"] if saved else None,
        "plan": ["screen", "human_review", "schedule_interview", "human_decision"],
        "mode": "deterministic-human-supervised",
    }


@router.get("/{application_id}")
def workflow_status(application_id: int, request: Request, user: HR):
    with connect(request.app.state.database_path) as db:
        return describe(db, get_application(db, application_id))


@router.post("/{application_id}/run")
def run_workflow(application_id: int, request: Request, user: HR):
    """Run the next safe automatic step and persist a resumable checkpoint."""
    with connect(request.app.state.database_path) as db:
        db.execute("BEGIN IMMEDIATE")
        application = get_application(db, application_id)
        state = describe(db, application)
        if state["next_step"] == "complete":
            raise HTTPException(status_code=409, detail="Application is already closed")
        step = state["next_step"]
        if step == "screen":
            job_row = db.execute("SELECT * FROM jobs WHERE id = ?", (application["job_id"],)).fetchone()
            if job_row is None:
                raise HTTPException(status_code=404, detail="Job not found")
            score = score_resume(job_data(job_row), application["resume_text"])
            serialized = json.dumps(score, ensure_ascii=False)
            db.execute(
                "UPDATE applications SET score_json = ?, updated_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now') WHERE id = ?",
                (serialized, application_id),
            )
            db.execute(
                "INSERT INTO audit_events (application_id, actor_id, action, details) VALUES (?, ?, ?, ?)",
                (application_id, user.id, "screened", serialized),
            )
        db.execute(
            """INSERT INTO recruitment_workflows (application_id, last_step) VALUES (?, ?)
               ON CONFLICT(application_id) DO UPDATE SET last_step = excluded.last_step,
               updated_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now')""",
            (application_id, step),
        )
        return describe(db, get_application(db, application_id))
