"""HR-managed synthetic jobs for the experimental PostgreSQL demo."""
import hashlib
import json
import re
from typing import Annotated

from fastapi import Depends, HTTPException, Request
from pydantic import BaseModel, Field, field_validator

from app.auth import User
from app.recruitment import job_data

DDL = '''CREATE TABLE IF NOT EXISTS job_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id text NOT NULL REFERENCES jobs(id), actor_id bigint NOT NULL REFERENCES users(id),
    action text NOT NULL, revision text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp())'''


class Job(BaseModel):
    id: str = Field(pattern=r'^[a-z0-9]+(?:-[a-z0-9]+)*$', min_length=1, max_length=64)
    title: str = Field(min_length=1, max_length=200)
    location: str = Field(min_length=1, max_length=200)
    required_skills: list[str] = Field(min_length=1, max_length=20)
    preferred_skills: list[str] = Field(default_factory=list, max_length=20)
    responsibilities: list[str] = Field(default_factory=list, max_length=20)

    @field_validator('title', 'location')
    @classmethod
    def text_value(cls, value):
        value = value.strip()
        if not value or any(ord(char) < 32 for char in value):
            raise ValueError('Enter a single-line value')
        return value

    @field_validator('required_skills', 'preferred_skills', 'responsibilities')
    @classmethod
    def list_values(cls, values):
        result = [value.strip() for value in values]
        if any(not value or len(value) > 80 or any(ord(char) < 32 for char in value) for value in result):
            raise ValueError('Each entry must contain 1 to 80 single-line characters')
        if len({value.casefold() for value in result}) != len(result):
            raise ValueError('Duplicate entries are not allowed')
        return result


class JobEdit(BaseModel):
    job: Job
    expected_revision: str = Field(pattern=r'^[0-9a-f]{64}$')


def revision(row):
    content = json.dumps(job_data(row), ensure_ascii=False, sort_keys=True, separators=(',', ':'))
    return hashlib.sha256(content.encode()).hexdigest()


def values(job):
    return (job.title, job.location, *(json.dumps(getattr(job, key), ensure_ascii=False) for key in
            ('required_skills', 'preferred_skills', 'responsibilities')))


def install_routes(app, connect, authenticate, authorize_locked):
    @app.get('/api/hr/jobs')
    def list_hr_jobs(request: Request, user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            rows = db.execute('SELECT * FROM jobs ORDER BY title,id FOR SHARE').fetchall()
            result = [{**job_data(row), 'revision': revision(row)} for row in rows]
            authorize_locked(db, request, user, 'hr')
            return result

    @app.post('/api/hr/jobs', status_code=201)
    def create_job(payload: Job, request: Request, user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            row = db.execute('''INSERT INTO jobs(id,title,location,required_skills,preferred_skills,responsibilities)
                VALUES (%s,%s,%s,%s,%s,%s) ON CONFLICT(id) DO NOTHING RETURNING *''',
                (payload.id, *values(payload))).fetchone()
            if row is None:
                raise HTTPException(status_code=409, detail='Job ID already exists')
            digest = revision(row)
            db.execute("INSERT INTO job_audit(job_id,actor_id,action,revision) VALUES (%s,%s,'created',%s)",
                       (payload.id,user.id,digest))
            authorize_locked(db, request, user, 'hr')
            return {**job_data(row), 'revision': digest}

    @app.put('/api/hr/jobs/{job_id}')
    def edit_job(job_id: str, payload: JobEdit, request: Request, user: Annotated[User, Depends(authenticate)]):
        if job_id != payload.job.id or not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', job_id):
            raise HTTPException(status_code=422, detail='Job ID does not match')
        with connect() as db:
            authorize_locked(db, request, user, 'hr')
            row = db.execute('SELECT * FROM jobs WHERE id=%s FOR UPDATE', (job_id,)).fetchone()
            if row is None:
                raise HTTPException(status_code=404, detail='Job not found')
            if revision(row) != payload.expected_revision:
                raise HTTPException(status_code=409, detail='Job changed; reload before editing')
            # Submissions take a SHARE lock on the same job before insertion.
            # Once applications exist, use a new job ID to preserve the basis of
            # previous keyword screenings, reviews, and decisions.
            if db.execute('SELECT 1 FROM applications WHERE job_id=%s LIMIT 1', (job_id,)).fetchone():
                raise HTTPException(status_code=409, detail='Job has applications; create a new job instead')
            updated = db.execute('''UPDATE jobs SET title=%s,location=%s,required_skills=%s,
                preferred_skills=%s,responsibilities=%s WHERE id=%s RETURNING *''',
                (*values(payload.job), job_id)).fetchone()
            digest = revision(updated)
            db.execute("INSERT INTO job_audit(job_id,actor_id,action,revision) VALUES (%s,%s,'updated',%s)",
                       (job_id,user.id,digest))
            authorize_locked(db, request, user, 'hr')
            return {**job_data(updated), 'revision': digest}
