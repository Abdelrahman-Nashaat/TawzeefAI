    @app.post('/api/auth/login')
    def login(payload: Login, request: Request, response: Response):
        with connect() as db:
            account = db.execute('SELECT * FROM users WHERE username=%s', (payload.username,)).fetchone()
        if not account or not verify_password(payload.password, account['password_hash']):
            raise HTTPException(status_code=401, detail='Invalid credentials')
        token = secrets.token_urlsafe(32)
        with connect() as db:
            try:
                now = int(time.time())
                issue_session(db, dialect='postgres', user_id=account['id'], expected_password_hash=account['password_hash'],
                              token_hash=token_digest(token), now=now, expires_at=now + SESSION_SECONDS)
            except InvalidAccount:
                raise HTTPException(status_code=401, detail='Invalid credentials') from None
            old = request.cookies.get(COOKIE_NAME)
            if old:
                db.execute('DELETE FROM sessions WHERE token_hash=%s', (token_digest(old),))
        response.set_cookie(COOKIE_NAME, token, max_age=SESSION_SECONDS, httponly=True, samesite='strict', path='/')
        return {key:account[key] for key in ('id','username','display_name','role')}

    @app.post('/api/auth/logout', status_code=204)
    def logout(request: Request):
        token = request.cookies.get(COOKIE_NAME)
        if token:
            with connect() as db:
                db.execute('DELETE FROM sessions WHERE token_hash=%s', (token_digest(token),))
        response = Response(status_code=204)
        response.delete_cookie(COOKIE_NAME, path='/', httponly=True, samesite='strict')
        return response

