class Login(BaseModel):
    username: str = Field(min_length=1, max_length=128)
    password: str = Field(min_length=1, max_length=256)


def create_postgres_app(*, seed_demo: bool) -> FastAPI:
    if not seed_demo:
        raise RuntimeError('PostgreSQL experimental mode requires synthetic demo mode')
    dsn = os.environ.get('TAWZEEF_POSTGRES_DSN')
    schema = os.environ.get('TAWZEEF_POSTGRES_SCHEMA', '')
    if not dsn or not _SCHEMA.fullmatch(schema):
        raise RuntimeError('Set a PostgreSQL DSN and an experimental schema name')

    @contextmanager
    def connect():
        with psycopg.connect(dsn, row_factory=dict_row) as db:
            db.execute(sql.SQL('SET LOCAL search_path TO {}, pg_catalog').format(sql.Identifier(schema)))
            yield db

    @asynccontextmanager
    async def lifespan(app):
        # Never claim an existing schema not explicitly created by this mode.
        with psycopg.connect(dsn, row_factory=dict_row) as db:
            db.execute('SELECT pg_advisory_xact_lock(hashtext(%s))', (schema,))
            exists = db.execute('SELECT 1 FROM pg_namespace WHERE nspname=%s', (schema,)).fetchone()
            if exists:
                marker = db.execute('''SELECT 1 FROM information_schema.tables
                    WHERE table_schema=%s AND table_name='metadata' ''', (schema,)).fetchone()
                if not marker:
                    raise RuntimeError('Experimental schema exists without a valid marker')
                db.execute(sql.SQL('SET LOCAL search_path TO {}, pg_catalog').format(sql.Identifier(schema)))
                versions = db.execute('SELECT version FROM metadata').fetchall()
                if len(versions) != 1 or versions[0]['version'] != _SCHEMA_VERSION:
                    raise RuntimeError('Unsupported experimental PostgreSQL schema version')
            else:
                db.execute(sql.SQL('CREATE SCHEMA {}').format(sql.Identifier(schema)))
                db.execute(sql.SQL('REVOKE ALL ON SCHEMA {} FROM PUBLIC').format(sql.Identifier(schema)))
                db.execute(sql.SQL('SET LOCAL search_path TO {}, pg_catalog').format(sql.Identifier(schema)))
                for statement in _DDL:
                    db.execute(statement)
                db.execute('INSERT INTO metadata VALUES (%s)', (_SCHEMA_VERSION,))
                for username, role in (('candidate','candidate'), ('candidate2','candidate'), ('hr','hr')):
                    db.execute('INSERT INTO users(username,display_name,role,password_hash) VALUES (%s,%s,%s,%s)',
                               (username, 'Demo ' + username, role, hash_password(username + '-demo-only')))
                jobs = json.loads(FIXTURE_FILE.read_text(encoding='utf-8'))['jobs']
                for job in jobs:
                    db.execute('INSERT INTO jobs VALUES (%s,%s,%s,%s,%s,%s)',
                               (job['id'], job['title'], job['location'],
                                *(json.dumps(job[key], ensure_ascii=False) for key in
                                  ('required_skills','preferred_skills','responsibilities'))))
        yield

    app = FastAPI(title='TawzeefAI experimental PostgreSQL submission API', lifespan=lifespan)
    app.add_middleware(TrustedHostMiddleware, allowed_hosts=['localhost', '127.0.0.1', '[::1]', 'testserver'])

    @app.middleware('http')
    async def check_origin(request: Request, call_next):
        peer = request.client.host if request.client else ''
        try:
            loopback = ipaddress.ip_address(peer).is_loopback
        except ValueError:
            loopback = peer == 'testclient'
        if not loopback:
            return JSONResponse({'detail': 'Local access only'}, status_code=403)
        if request.method not in {'GET','HEAD','OPTIONS'}:
            origin = request.headers.get('origin')
            if origin:
                parsed = urlsplit(origin)
                if (parsed.scheme, parsed.netloc) != (request.url.scheme, request.headers.get('host')):
                    return JSONResponse({'detail':'Cross-origin request denied'}, status_code=403)
            if request.headers.get('sec-fetch-site', '').lower() == 'cross-site':
                return JSONResponse({'detail':'Cross-origin request denied'}, status_code=403)
        return await call_next(request)

    def authenticate(request: Request) -> User:
        token = request.cookies.get(COOKIE_NAME, '')
        with connect() as db:
            row = session_user(db, dialect='postgres', token_hash=token_digest(token), now=int(time.time())) if token else None
        if not row:
            raise HTTPException(status_code=401, detail='Authentication required')
        return User(**dict(row))

    def authorize_locked(db, request, user, role=None):
        token = request.cookies.get(COOKIE_NAME, '')
        actor = db.execute('''SELECT u.id,u.username,u.role FROM sessions s JOIN users u ON u.id=s.user_id
            WHERE s.token_hash=%s AND s.expires_at>%s AND u.active=1 FOR SHARE OF s,u''',
            (token_digest(token), int(time.time()))).fetchone() if token else None
        if not actor or actor['id'] != user.id or actor['username'] != user.username:
            raise HTTPException(status_code=401, detail='Authentication required')
        if actor['role'] != user.role or (role and actor['role'] != role):
            raise HTTPException(status_code=403, detail='Access denied')

    @app.get('/api/health')
    def health():
        return {'status':'ok', 'mode':'postgres-experimental-submission-only'}

    @app.post('/api/auth/login')
    def login(payload: Login, request: Request, response: Response):
        with connect() as db:
            account = db.execute('SELECT * FROM users WHERE username=%s', (payload.username,)).fetchone()
        if not account or not verify_password(payload.password, account['password_hash']):
            raise HTTPException(status_code=401, detail='Invalid credentials')
        token = secrets.token_urlsafe(32)
        with connect() as db:
            try:
                now = int(time.time())
                issue_session(db, dialect='postgres', user_id=account['id'], expected_password_hash=account['password_hash'],
                              token_hash=token_digest(token), now=now, expires_at=now + SESSION_SECONDS)
            except InvalidAccount:
                raise HTTPException(status_code=401, detail='Invalid credentials') from None
            old = request.cookies.get(COOKIE_NAME)
            if old:
                db.execute('DELETE FROM sessions WHERE token_hash=%s', (token_digest(old),))
        response.set_cookie(COOKIE_NAME, token, max_age=SESSION_SECONDS, httponly=True, samesite='strict', path='/')
        return {key:account[key] for key in ('id','username','display_name','role')}

    @app.post('/api/auth/logout', status_code=204)
    def logout(request: Request):
        token = request.cookies.get(COOKIE_NAME)
        if token:
            with connect() as db:
                db.execute('DELETE FROM sessions WHERE token_hash=%s', (token_digest(token),))
        response = Response(status_code=204)
        response.delete_cookie(COOKIE_NAME, path='/', httponly=True, samesite='strict')
        return response

    @app.get('/api/auth/me')
    def me(user: Annotated[User, Depends(authenticate)]):
        return {'id':user.id, 'username':user.username, 'display_name':user.display_name, 'role':user.role}

    @app.get('/api/jobs')
    def jobs(request: Request, user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user)
            result = [job_data(row) for row in db.execute('SELECT * FROM jobs ORDER BY title')]
            authorize_locked(db, request, user)
            return result

    @app.post('/api/applications', status_code=201)
    async def apply(request: Request, user: Annotated[User, Depends(authenticate)], job_id: str, filename: str,
                    ocr: bool = False):
        if user.role != 'candidate':
            raise HTTPException(status_code=403, detail='Access denied')
        if ocr:
            raise HTTPException(status_code=422, detail='OCR is unavailable in experimental PostgreSQL mode')
        if len(filename) > 255 or not filename or '\x00' in filename:
            raise HTTPException(status_code=400, detail='Invalid filename')
        filename = PurePath(filename.replace('\\','/')).name
        with connect() as db:
            authorize_locked(db, request, user, 'candidate')
            if not db.execute('SELECT 1 FROM jobs WHERE id=%s', (job_id,)).fetchone():
                raise HTTPException(status_code=404, detail='Job not found')
        chunks = bytearray()
        async for chunk in request.stream():
            if len(chunks) + len(chunk) > MAX_FILE_BYTES:
                raise HTTPException(status_code=413, detail='File exceeds 5 MiB limit')
            chunks.extend(chunk)
        try:
            content = await run_in_threadpool(extract_document_text, filename, bytes(chunks))
        except DocumentTextError as exc:
            raise HTTPException(status_code=422, detail={'code':exc.code, 'message':str(exc)}) from exc
        with connect() as db:
            authorize_locked(db, request, user, 'candidate')
            application_id = submit_application(db, dialect='postgres', candidate_id=user.id, job_id=job_id,
                                                filename=filename, resume_text=content, extraction_json=None)
            if application_id is None:
                raise HTTPException(status_code=404, detail='Job not found')
            row = db.execute('SELECT * FROM applications WHERE id=%s', (application_id,)).fetchone()
            authorize_locked(db, request, user, 'candidate')
            return application_view(row, user)

    @app.get('/api/applications')
    def applications(request: Request, user: Annotated[User, Depends(authenticate)]):
        with connect() as db:
            authorize_locked(db, request, user)
            if user.role == 'hr':
                rows = db.execute('SELECT * FROM applications ORDER BY id DESC').fetchall()
            elif user.role == 'candidate':
                rows = db.execute('SELECT * FROM applications WHERE candidate_id=%s ORDER BY id DESC', (user.id,)).fetchall()
            else:
                raise HTTPException(status_code=403, detail='Access denied')
            result = [application_view(row, user) for row in rows]
            authorize_locked(db, request, user)
            return result

    return app
