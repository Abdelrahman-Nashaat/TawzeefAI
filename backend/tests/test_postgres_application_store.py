"""Exercise real PostgreSQL transactions against a disposable synthetic schema."""

import os
import threading
import uuid

import pytest

psycopg = pytest.importorskip('psycopg')
from psycopg import sql
from psycopg.rows import dict_row

from app.application_store import submit_application


@pytest.fixture
def database():
    dsn = os.environ.get('TAWZEEF_TEST_POSTGRES_DSN')
    if not dsn:
        pytest.skip('Set TAWZEEF_TEST_POSTGRES_DSN to a disposable PostgreSQL database')
    schema = 'tawzeef_submit_test_' + uuid.uuid4().hex
    with psycopg.connect(dsn, autocommit=True) as admin:
        admin.execute(sql.SQL('CREATE SCHEMA {}').format(sql.Identifier(schema)))
        try:
            admin.execute(sql.SQL('SET search_path TO {}, pg_catalog').format(sql.Identifier(schema)))
            admin.execute('CREATE TABLE users(id bigint PRIMARY KEY)')
            admin.execute('CREATE TABLE jobs(id text PRIMARY KEY)')
            admin.execute('''CREATE TABLE applications(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                candidate_id bigint NOT NULL REFERENCES users(id), job_id text NOT NULL REFERENCES jobs(id),
                filename text NOT NULL, resume_text text NOT NULL, extraction_json text)''')
            admin.execute('''CREATE TABLE hr_notifications(application_id bigint NOT NULL REFERENCES applications(id),
                submitted_job_id text NOT NULL)''')
            admin.execute('''CREATE TABLE audit_events(application_id bigint NOT NULL REFERENCES applications(id),
                actor_id bigint NOT NULL REFERENCES users(id), action text NOT NULL, details text NOT NULL)''')
            admin.execute('CREATE TABLE provisional_job_revisions(job_id text PRIMARY KEY REFERENCES jobs(id), revision bigint NOT NULL)')
            admin.execute('''CREATE TABLE provisional_application_revisions(application_id bigint PRIMARY KEY
                REFERENCES applications(id), revision bigint NOT NULL)''')
            admin.execute('''CREATE TABLE provisional_snapshots(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                application_id bigint NOT NULL REFERENCES applications(id), job_id text NOT NULL REFERENCES jobs(id),
                job_revision bigint NOT NULL, assignment_revision bigint NOT NULL, source_review_status text NOT NULL,
                snapshot_kind text NOT NULL, created_by bigint NOT NULL REFERENCES users(id))''')
            admin.execute('INSERT INTO users VALUES (1)')
            admin.execute("INSERT INTO jobs VALUES ('job-1')")
            admin.execute("INSERT INTO provisional_job_revisions VALUES ('job-1', 3)")
            yield dsn, schema
        finally:
            admin.execute(sql.SQL('DROP SCHEMA {} CASCADE').format(sql.Identifier(schema)))


def connection(database):
    dsn, schema = database
    db = psycopg.connect(dsn, row_factory=dict_row)
    db.execute(sql.SQL('SET search_path TO {}, pg_catalog').format(sql.Identifier(schema)))
    db.commit()
    return db


def submit(db, job='job-1'):
    return submit_application(db, dialect='postgres', candidate_id=1, job_id=job,
                              filename='synthetic.pdf', resume_text='fictional', extraction_json=None)


def test_submission_writes_all_records_with_current_revision(database):
    with connection(database) as db:
        application_id = submit(db)
    with connection(database) as db:
        assert db.execute('SELECT resume_text FROM applications WHERE id=%s', (application_id,)).fetchone()['resume_text'] == 'fictional'
        assert db.execute('SELECT submitted_job_id FROM hr_notifications WHERE application_id=%s', (application_id,)).fetchone()['submitted_job_id'] == 'job-1'
        assert db.execute('SELECT action FROM audit_events WHERE application_id=%s', (application_id,)).fetchone()['action'] == 'submitted'
        snapshot = db.execute('SELECT job_revision,assignment_revision,snapshot_kind FROM provisional_snapshots WHERE application_id=%s', (application_id,)).fetchone()
        assert dict(snapshot) == {'job_revision': 3, 'assignment_revision': 0, 'snapshot_kind': 'pending'}


def test_failure_rolls_back_application_and_related_records(database):
    with connection(database) as db:
        db.execute("ALTER TABLE provisional_snapshots ADD CONSTRAINT no_pending CHECK (snapshot_kind <> 'pending')")
    with connection(database) as db:
        with pytest.raises(psycopg.errors.CheckViolation), db.transaction():
            submit(db)
        for table in ('applications', 'hr_notifications', 'audit_events', 'provisional_snapshots'):
            assert db.execute(sql.SQL('SELECT count(*) AS n FROM {}').format(sql.Identifier(table))).fetchone()['n'] == 0


def test_missing_job_does_not_create_partial_records(database):
    with connection(database) as db:
        assert submit(db, job='missing') is None
        assert db.execute('SELECT count(*) AS n FROM applications').fetchone()['n'] == 0


def test_autocommit_is_rejected(database):
    dsn, _ = database
    with psycopg.connect(dsn, autocommit=True, row_factory=dict_row) as db, \
            pytest.raises(ValueError, match='autocommit disabled'):
        submit(db)


def test_job_change_waits_until_submission_snapshot_commits(database):
    started = threading.Event()
    done = threading.Event()
    failures = []

    def update_job():
        try:
            with connection(database) as db:
                started.set()
                db.execute("UPDATE jobs SET id=id WHERE id='job-1'")
                db.execute("UPDATE provisional_job_revisions SET revision=4 WHERE job_id='job-1'")
        except Exception as error:  # noqa: BLE001 - report worker failures to the test
            failures.append(error)
        finally:
            done.set()

    with connection(database) as db:
        application_id = submit(db)
        thread = threading.Thread(target=update_job, daemon=True)
        thread.start()
        assert started.wait(10)
        assert not done.wait(0.3)
        db.commit()
        thread.join(10)
        assert not thread.is_alive() and not failures
    with connection(database) as db:
        snapshot = db.execute('SELECT job_revision FROM provisional_snapshots WHERE application_id=%s',
                              (application_id,)).fetchone()
        assert snapshot['job_revision'] == 3
        assert db.execute("SELECT revision FROM provisional_job_revisions WHERE job_id='job-1'").fetchone()['revision'] == 4
